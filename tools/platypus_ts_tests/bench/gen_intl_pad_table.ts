// Writes iron_ts_rt/src/intl_pad.rs: for each main-market locale, whether ICU4C pads a numeric
// month, day and hour to two digits in the default numeric patterns (CLDR `availableFormats`
// `yMd`, `Md`, `Hm`, `Hms`). ICU4X's semantic patterns do not carry this, so `Intl.DateTimeFormat`
// looks it up. The hour depends on the width asked for the minute (and second), so both are probed.
// Run it again when the locale list or the reference engine changes:
//   bun bench/gen_intl_pad_table.ts
// The locale list is the `icu-lite` data set (docs/research/iron-ts-intl-datetime.md).
const LOCALES = [
  "en-US", "en-GB", "en-CA", "en-AU", "en-IN", "de-DE", "de-AT", "de-CH", "fr-FR", "fr-CA", "es-ES", "es-MX", "it-IT", "pt-BR", "pt-PT",
  "nl-NL", "sv-SE", "da-DK", "nb-NO", "fi-FI", "pl-PL", "cs-CZ", "el-GR", "tr-TR", "ru-RU", "uk-UA", "ja-JP", "ko-KR", "zh-CN", "zh-TW", "hi-IN",
];
const day = new Date(2026, 2, 8, 3, 30, 0);
const part = (loc: string, opts: Intl.DateTimeFormatOptions, type: string) =>
  new Intl.DateTimeFormat(loc, opts).formatToParts(day).find((p) => p.type === type)?.value ?? "";
let rows = "";
for (const loc of LOCALES) {
  const ymd = { year: "numeric", month: "numeric", day: "numeric" } as const;
  const md = { month: "numeric", day: "numeric" } as const;
  const month = part(loc, ymd, "month").length > 1;
  const dayPad = part(loc, ymd, "day").length > 1;
  const monthMd = part(loc, md, "month").length > 1;
  const dayMd = part(loc, md, "day").length > 1;
  // A locale whose own cycle is 24-hour is probed as it is (the usual call); otherwise with h23.
  const own24 = /^h2[34]$/.test(new Intl.DateTimeFormat(loc, { hour: "numeric" }).resolvedOptions().hourCycle ?? "");
  const cycle = own24 ? {} : { hourCycle: "h23" as const };
  const hour = (minute: "numeric" | "2-digit", seconds: boolean) =>
    part(loc, { hour: "numeric", minute, ...(seconds ? { second: minute } : {}), ...cycle }, "hour").length > 1;
  rows += `    ("${loc}", ${month}, ${dayPad}, ${monthMd}, ${dayMd}, ${hour("numeric", false)}, ${hour("2-digit", false)}, ${hour("numeric", true)}, ${hour("2-digit", true)}),\n`;
}
const out = `//! GENERATED by bench/gen_intl_pad_table.ts from the reference engine's ICU4C; do not edit.
//! Per locale: does a numeric month / day pad to two digits in the full numeric date (\`yMd\`) and in
//! the month-day pattern (\`Md\`), and does a numeric hour pad in 24-hour time (\`Hm\` / \`Hms\`, with
//! the minute written numeric or 2-digit).

/// Which numeric fields a locale pads.
#[derive(Clone, Copy)]
pub(crate) struct Padding {
    pub month: bool,
    pub day: bool,
    pub month_md: bool,
    pub day_md: bool,
    /// Hour with minutes, minute numeric / 2-digit.
    pub hm_numeric: bool,
    pub hm_two_digit: bool,
    /// Hour with minutes and seconds, minute and second numeric / 2-digit.
    pub hms_numeric: bool,
    pub hms_two_digit: bool,
}

#[allow(clippy::too_many_arguments)]
const fn p(
    month: bool,
    day: bool,
    month_md: bool,
    day_md: bool,
    hm_numeric: bool,
    hm_two_digit: bool,
    hms_numeric: bool,
    hms_two_digit: bool,
) -> Padding {
    Padding { month, day, month_md, day_md, hm_numeric, hm_two_digit, hms_numeric, hms_two_digit }
}

const TABLE: &[(&str, Padding)] = &[
${rows.replace(/\("([^"]+)", ([^)]*)\),\n/g, '("$1", p($2)),\n')}];

/// The padding of a locale tag: the exact tag, else the language alone.
pub(crate) fn padding(tag: &str) -> Option<Padding> {
    let lang = tag.split('-').next().unwrap_or(tag);
    TABLE
        .iter()
        .find(|r| r.0 == tag)
        .or_else(|| TABLE.iter().find(|r| r.0.split('-').next() == Some(lang)))
        .map(|r| r.1)
}
`;
await Bun.write(import.meta.dir + "/../../iron_ts_rt/src/intl_pad.rs", out);
console.log("wrote", LOCALES.length, "locales");
