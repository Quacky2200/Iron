//! Compiles the zombie game's sim.ts with `iron_ts` and links the object into this crate's targets.
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let src_path = manifest.join("fixtures/sim.ts");
    println!("cargo:rerun-if-changed={}", src_path.display());
    println!("cargo:rerun-if-changed=build.rs");
    let src = std::fs::read_to_string(&src_path).expect("read sim.ts");
    let t = std::time::Instant::now();
    let out = iron_ts::compile_source(&src, "speed").unwrap_or_else(|e| panic!("iron_ts: {e}"));
    println!(
        "cargo:warning=iron_ts compiled sim.ts in {:?} (lower {:?}, cranelift {:?})",
        t.elapsed(),
        out.lower_time,
        out.codegen_time
    );
    let dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let obj = dir.join("sim.obj");
    std::fs::write(&obj, &out.object).unwrap();
    std::fs::write(dir.join("sim_bindings.rs"), &out.bindings).unwrap();
    std::fs::write(dir.join("sim.ir.txt"), &out.ir).unwrap();
    println!("cargo:rustc-link-arg={}", obj.display());

    // Other modules linked next to it (symbols `ts_<prefix>*`, bindings `<name>_bindings.rs`).
    for (name, prefix, base) in [
        ("sine", "sine_", 1000),
        ("gap", "gap_", 2000),
        ("closures", "clo_", 3000),
        ("globals", "glob_", 4000),
        ("loops", "loop_", 5000),
        ("switches", "sw_", 6000),
        ("destructure", "des_", 7000),
        ("params", "par_", 8000),
        ("mathlib", "ml_", 9000),
        ("arraylib", "al_", 10000),
        ("classes", "cls_", 11000),
        ("inherit", "inh_", 12000),
        ("props", "prop_", 13000),
        ("engine", "eng_", 14000),
        ("scene", "scn_", 15000),
        ("strings", "str_", 16000),
        ("errors", "err_", 17000),
        ("stdlib", "std_", 18000),
        ("collections", "col_", 19000),
        ("json", "json_", 20000),
        ("regexp", "re_", 21000),
        ("regexp2", "re2_", 22000),
        ("date", "dt_", 23000),
        ("intl", "in_", 24000),
        ("numfmt", "nf_", 25000),
        ("datefmt", "df_", 26000),
        ("uri", "uri_", 27000),
        ("errors2", "e2_", 28000),
        ("intl4", "i4_", 29000),
        ("typed", "ty_", 30000),
        ("bigint", "bi_", 31000),
        ("logic", "lg_", 32000),
        ("iterators", "itr_", 33000),
        ("generators", "gn_", 34000),
        ("symbols", "sym_", 700),
        ("generators2", "gn2_", 800),
        ("promises", "pr_", 900),
        ("buffers", "bf_", 1000),
        ("clone", "cl_", 1100),
        ("weak", "wk_", 1200),
        ("segmenter", "sg_", 1300),
        ("locale", "lc_", 1400),
        ("dispnames", "dn_", 1500),
        ("temporal", "tp_", 1600),
        ("zoned", "zn_", 1700),
        ("monthday", "md_", 1800),
        ("rounding", "rd_", 1900),
        ("canon", "cn_", 2000),
        ("fparts", "fp_", 2100),
        ("resolved", "rs_", 2200),
        ("components", "cmp_", 2300),
        ("ui", "uic_", 2500),
        ("sine_demo", "sd_", 2600),
        ("ui_perf", "uip_", 2700),
        ("engine2", "en2_", 2800),
        ("sine_demo_full", "sdf_", 2900),
        ("generics", "gx_", 2400),
        ("nullbool", "nb_", 3000),
        ("components2", "cm2_", 3100),
        ("task", "tsk_", 4200),
        ("comp_life", "clf_", 5200),
        ("random", "rnd_", 3200),
        ("layers", "lyr_", 3300),
        ("prefs", "prf_", 3400),
        ("assets", "ast_", 3500),
        ("app", "apc_", 3600),
        ("clock", "clk_", 3700),
        ("inputs", "inp_", 3800),
        ("inputs2", "in2_", 3900),
        ("timespan", "tsp_", 4000),
        ("datetime", "dtm_", 4100),
        ("mathf", "mtf_", 4300),
        ("vectors", "vct_", 4400),
        ("rotations", "rot_", 4500),
        ("shapes", "shp_", 4600),
        ("anim_clips", "acl_", 4700),
        ("anim_player", "apl_", 4800),
        ("anim_animator", "ani_", 4900),
        ("scene_objects", "sob_", 5000),
        ("comp_query", "cqy_", 5100),
        ("scenes", "scf_", 5300),
        ("physics", "phy_", 5400),
        ("contacts", "cnt_", 6000),
    ] {
        let path = manifest.join(format!("bench/{name}.ts"));
        println!("cargo:rerun-if-changed={}", path.display());
        // The engine API a module may call (generated by `#[iron_api]` in iron_demo_api).
        let manifests: Vec<String> = match name {
            "engine" => vec![iron_demo_api::manifest_json()],
            // The real engine's scene API, generated by `#[iron_api]` in `iron_scene`.
            "ui" | "ui_perf" => vec![iron_ts_ui::manifest_json()],
            "engine2" | "sine_demo_full" | "random" | "layers" | "prefs" | "assets" | "app"
            | "clock" | "inputs" | "inputs2" | "timespan" | "datetime" | "mathf" | "vectors"
            | "rotations" | "shapes" | "anim_clips" | "anim_player" | "anim_animator"
            | "scene_objects" | "comp_query" | "comp_life" | "scenes" | "physics" | "contacts" => {
                engine_manifests()
            }
            "scene" | "components" | "components2" | "sine_demo" => {
                let mut v = vec![iron_scene::api::scene_api::MANIFEST.to_json()];
                v.extend(iron_engine_api::iron_math::manifests());
                v
            }
            _ => vec![],
        };
        let compiled = iron_ts::compile_with_manifests(
            &std::fs::read_to_string(&path).unwrap(),
            "speed",
            prefix,
            base,
            &manifests,
        );
        let out = match compiled {
            Ok(out) => out,
            Err(e) => panic!("iron_ts {name}: {e}"),
        };
        let obj = dir.join(format!("{name}.obj"));
        std::fs::write(&obj, &out.object).unwrap();
        std::fs::write(dir.join(format!("{name}_bindings.rs")), &out.bindings).unwrap();
        println!("cargo:rustc-link-arg={}", obj.display());
    }
}

/// Every engine API namespace a compiled program may call.
fn engine_manifests() -> Vec<String> {
    let mut all = vec![iron_scene::api::scene_api::MANIFEST.to_json()];
    all.extend(iron_engine_api::manifests());
    all.extend(iron_scenes::manifests());
    all.extend(iron_physics_api::manifests());
    all
}
