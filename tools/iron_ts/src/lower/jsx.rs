/// Does the program use JSX or the hooks?
pub fn wanted(src: &str) -> bool {
    src.contains("</")
        || src.contains("/>")
        || src.contains("<>")
        || src.contains("createRoot(")
        || [
            "useState",
            "useEffect",
            "useMemo",
            "useCallback",
            "useRef",
            "useReducer",
            "useContext",
            "createContext",
            "memo",
            "forwardRef",
        ]
        .iter()
        .any(|h| src.contains(&format!("{h}(")) || src.contains(&format!("{h}<")))
}

/// Is this expression an element already (a JSX element, or a conditional of those)?
fn is_element_expr(e: &Expression<'_>) -> bool {
    matches!(
        e.get_inner_expression(),
        Expression::JSXElement(_) | Expression::JSXFragment(_)
    )
}

/// The intrinsic element a capitalised `@iron/react` component name stands for.
fn intrinsic_alias(name: &str) -> Option<&'static str> {
    Some(match name {
        "Text" => "text",
        "Span" => "span",
        "Input" => "input",
        "TextArea" => "textarea",
        "Image" => "image",
        "List" => "list",
        "Dialog" => "dialog",
        _ => return None,
    })
}

/// A stable component id from its name (FNV-1a, 31 bits).
fn component_id(name: &str) -> u32 {
    let mut h: u32 = 0x811c_9dc5;
    for b in name.bytes() {
        h ^= u32::from(b);
        h = h.wrapping_mul(0x0100_0193);
    }
    h & 0x7fff_ffff
}

/// A JavaScript string literal for `s`.
fn js_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// JSX text with React's whitespace rules: lines are trimmed, blank lines dropped, the rest joined by spaces.
fn jsx_text(raw: &str) -> String {
    let lines: Vec<&str> = raw.split('\n').collect();
    let last = lines.len() - 1;
    let mut parts = Vec::new();
    for (i, l) in lines.iter().enumerate() {
        let mut l = l.replace('\t', " ");
        if i != 0 {
            l = l.trim_start().to_string();
        }
        if i != last {
            l = l.trim_end().to_string();
        }
        if !l.is_empty() {
            parts.push(l);
        }
    }
    parts.join(" ")
}

struct Edit {
    start: usize,
    end: usize,
    text: String,
}

struct Finder<'s> {
    src: &'s str,
    edits: Vec<Edit>,
    error: Option<String>,
    /// `const Fast = memo(Slow)`: `Fast` -> `Slow`.
    memo: HashMap<String, String>,
    /// Components made by `forwardRef`: they take the ref as a second argument.
    forward: HashSet<String>,
    /// The setters of `const [x, setX] = useState(..)` anywhere in the program.
    setters: HashSet<String>,
    /// Top-level functions, classes and constants of the program (they shadow the `@iron/react` aliases).
    declared: HashSet<String>,
    /// The ones that are functions: `useState(read)` calls `read` for the first value.
    declared_fns: HashSet<String>,
}

impl<'s> Finder<'s> {
    fn slice(&self, sp: oxc_span::Span) -> &'s str {
        &self.src[sp.start as usize..sp.end as usize]
    }

    fn fail(&mut self, msg: String) {
        if self.error.is_none() {
            self.error = Some(msg);
        }
    }

    fn line(&self, offset: u32) -> usize {
        self.src[..offset as usize].matches('\n').count() + 1
    }

    /// The text of an attribute value.
    fn attr_value(&mut self, v: &Option<JSXAttributeValue<'_>>, at: u32) -> String {
        match v {
            None => "true".into(),
            Some(JSXAttributeValue::StringLiteral(s)) => js_string(s.value.as_str()),
            Some(JSXAttributeValue::ExpressionContainer(c)) => match &c.expression {
                JSXExpression::EmptyExpression(_) => {
                    self.fail(format!("line {}: an empty attribute value", self.line(at)));
                    "null".into()
                }
                e => self.slice(e.span()).to_string(),
            },
            Some(_) => {
                self.fail(format!(
                    "line {}: an element as an attribute value is not supported",
                    self.line(at)
                ));
                "null".into()
            }
        }
    }

    fn element_text(&mut self, e: &JSXElement<'_>) -> String {
        let open = &e.opening_element;
        let at = open.span.start;
        let (name, is_component) = match &open.name {
            JSXElementName::Identifier(i) => (i.name.to_string(), false),
            JSXElementName::IdentifierReference(i) => (i.name.to_string(), true),
            // `<Theme.Provider value={v}>`
            JSXElementName::MemberExpression(m) if m.property.name == "Provider" => {
                if let JSXMemberExpressionObject::IdentifierReference(ctx) = &m.object {
                    return self.provider_text(ctx.name.as_str(), e);
                }
                self.fail(format!(
                    "line {}: a provider is `Name.Provider`",
                    self.line(at)
                ));
                return String::new();
            }
            _ => {
                self.fail(format!(
                    "line {}: only plain tag names are supported",
                    self.line(at)
                ));
                return String::new();
            }
        };
        // `<Text>`, `<Input>` ... from `@iron/react` are the intrinsic elements, unless the program
        // declares a component of that name.
        let (name, is_component) = match intrinsic_alias(&name) {
            Some(lower) if is_component && !self.declared.contains(&name) => {
                (lower.to_string(), false)
            }
            _ => (name, is_component),
        };
        if is_component {
            return self.component_text(&name, e);
        }
        let mut out = format!("Ui.begin({})", js_string(&name));
        for item in &open.attributes {
            let a = match item {
                JSXAttributeItem::Attribute(a) => a,
                // `{...obj}`: the fields of a typed object become attributes (see `Ui.attrObj`).
                JSXAttributeItem::SpreadAttribute(sp) => {
                    let t = self.slice(sp.argument.span()).to_string();
                    out = format!("Ui.attrObj({out}, {t})");
                    continue;
                }
            };
            let JSXAttributeName::Identifier(n) = &a.name else {
                self.fail(format!(
                    "line {}: namespaced attributes are not supported",
                    self.line(at)
                ));
                return out;
            };
            let n = n.name.as_str();
            match n {
                "key" => {
                    let v = self.attr_value(&a.value, at);
                    out = format!("Ui.key({out}, {v})");
                }
                "ref" => {
                    let v = self.attr_value(&a.value, at);
                    out = format!("Ui.ref({out}, {v})");
                }
                "style" => {
                    let Some(JSXAttributeValue::ExpressionContainer(c)) = &a.value else {
                        self.fail(format!(
                            "line {}: style must be {{{{ ... }}}}",
                            self.line(at)
                        ));
                        return out;
                    };
                    let literal = match c.expression.as_expression() {
                        Some(Expression::ObjectExpression(o))
                            if o.properties
                                .iter()
                                .all(|p| matches!(p, ObjectPropertyKind::ObjectProperty(_))) =>
                        {
                            Some(o)
                        }
                        _ => None,
                    };
                    let Some(o) = literal else {
                        // A variable, a call, an object with spread: its fields become style
                        // properties (see `Ui.styleObj`).
                        let Some(e) = c.expression.as_expression() else {
                            self.fail(format!("line {}: an empty style", self.line(at)));
                            return out;
                        };
                        let t = self.slice(e.span()).to_string();
                        out = format!("Ui.styleObj({out}, {t})");
                        continue;
                    };
                    for p in &o.properties {
                        let ObjectPropertyKind::ObjectProperty(p) = p else {
                            self.fail(format!("line {}: spread in style", self.line(at)));
                            return out;
                        };
                        let key = match &p.key {
                            PropertyKey::StaticIdentifier(k) => k.name.to_string(),
                            PropertyKey::StringLiteral(k) => k.value.to_string(),
                            _ => {
                                self.fail(format!(
                                    "line {}: style keys must be plain names",
                                    self.line(at)
                                ));
                                return out;
                            }
                        };
                        let v = self.slice(p.value.span()).to_string();
                        out = format!("Ui.style({out}, {}, {v})", js_string(&key));
                    }
                }
                n if n.len() > 2 && n.starts_with("on") && n.as_bytes()[2].is_ascii_uppercase() => {
                    let v = self.attr_value(&a.value, at);
                    let mut kind = n[2..].to_lowercase();
                    let mut capture = false;
                    if let Some(k) = kind.strip_suffix("capture") {
                        kind = k.to_string();
                        capture = true;
                    }
                    if kind == "change" {
                        kind = "input".into();
                    }
                    if capture {
                        kind.push_str(":capture");
                    }
                    out = format!("Ui.on({out}, {}, __handler({v}))", js_string(&kind));
                }
                n => {
                    let v = self.attr_value(&a.value, at);
                    out = format!("Ui.attr({out}, {}, {v})", js_string(n));
                }
            }
        }
        self.children_text(&mut out, &e.children, at);
        out
    }

    /// The text of a child expression. `{cond && <x/>}` is no element when `cond` is false (an
    /// empty fragment), as in React.
    fn conditional_child(&mut self, e: &Expression<'_>) -> String {
        if let Expression::LogicalExpression(l) = e.get_inner_expression()
            && l.operator == LogicalOperator::And
            && matches!(
                l.right.get_inner_expression(),
                Expression::JSXElement(_) | Expression::JSXFragment(_)
            )
        {
            return format!(
                "(({}) ? {} : Ui.fragment())",
                self.slice(l.left.span()),
                self.slice(l.right.span())
            );
        }
        self.slice(e.span()).to_string()
    }

    fn children_text(&mut self, out: &mut String, children: &[JSXChild<'_>], at: u32) {
        for c in children {
            match c {
                JSXChild::Text(t) => {
                    let s = jsx_text(t.value.as_str());
                    if !s.is_empty() {
                        *out = format!("Ui.child({out}, {})", js_string(&s));
                    }
                }
                JSXChild::ExpressionContainer(c) => match &c.expression {
                    JSXExpression::EmptyExpression(_) => {}
                    e => {
                        let t = match e.as_expression() {
                            Some(x) => self.conditional_child(x),
                            None => self.slice(e.span()).to_string(),
                        };
                        *out = format!("Ui.child({out}, {t})");
                    }
                },
                JSXChild::Element(el) => {
                    let t = self.slice(el.span).to_string();
                    *out = format!("Ui.child({out}, {t})");
                }
                JSXChild::Fragment(f) => {
                    let t = self.slice(f.span).to_string();
                    *out = format!("Ui.child({out}, {t})");
                }
                JSXChild::Spread(_) => self.fail(format!(
                    "line {}: spread children are not supported",
                    self.line(at)
                )),
            }
        }
    }

    fn component_text(&mut self, name: &str, e: &JSXElement<'_>) -> String {
        let open = &e.opening_element;
        let at = open.span.start;
        let target = self
            .memo
            .get(name)
            .cloned()
            .unwrap_or_else(|| name.to_string());
        let is_memo = target != name;
        let is_forward = self.forward.contains(&target);
        let mut props = Vec::new();
        let mut dep_values = Vec::new();
        let mut ref_value = None;
        let mut key = None;
        for item in &open.attributes {
            let a = match item {
                JSXAttributeItem::Attribute(a) => a,
                JSXAttributeItem::SpreadAttribute(sp) => {
                    if is_memo {
                        self.fail(format!(
                            "line {}: a memo component cannot take spread props",
                            self.line(at)
                        ));
                    }
                    props.push(format!("...{}", self.slice(sp.argument.span())));
                    continue;
                }
            };
            let JSXAttributeName::Identifier(n) = &a.name else {
                self.fail(format!("line {}: namespaced props", self.line(at)));
                return String::new();
            };
            let v = self.attr_value(&a.value, at);
            if n.name == "key" {
                key = Some(v);
            } else if n.name == "ref" && is_forward {
                ref_value = Some(v);
            } else {
                dep_values.push(v.clone());
                props.push(format!("{}: {v}", n.name));
            }
        }
        // `children: ReactNode` is a list of elements (`UiElement[]`). Text, numbers and lists in
        // it become elements: `Ui.child(Ui.fragment(), x)` accepts each of them.
        let mut kids = Vec::new();
        for c in &e.children {
            match c {
                JSXChild::Element(el) => kids.push(self.slice(el.span).to_string()),
                JSXChild::Fragment(f) => kids.push(self.slice(f.span).to_string()),
                JSXChild::ExpressionContainer(c) => {
                    if let Some(x) = c.expression.as_expression() {
                        let t = self.conditional_child(x);
                        kids.push(if is_element_expr(x) {
                            t
                        } else {
                            format!("Ui.child(Ui.fragment(), {t})")
                        });
                    }
                }
                JSXChild::Text(t) => {
                    let s = jsx_text(t.value.as_str());
                    if !s.is_empty() {
                        kids.push(format!("Ui.child(Ui.fragment(), {})", js_string(&s)));
                    }
                }
                JSXChild::Spread(_) => self.fail(format!(
                    "line {}: spread children are not supported",
                    self.line(at)
                )),
            }
        }
        if !kids.is_empty() {
            props.push(format!("children: [{}]", kids.join(", ")));
        }
        let call = if is_forward {
            format!(
                "{target}({{ {} }}, {})",
                props.join(", "),
                ref_value.as_deref().unwrap_or("null")
            )
        } else if props.is_empty() {
            format!("{target}()")
        } else {
            format!("{target}({{ {} }})", props.join(", "))
        };
        let mut out = format!(
            "Ui.component({}, (): UiElement => {call})",
            component_id(name)
        );
        if let Some(k) = key {
            out = format!("Ui.key({out}, {k})");
        }
        if is_memo {
            // The props are the component's dependencies: equal ones skip the render.
            let mut seq = vec!["Ui.depsBegin()".to_string()];
            seq.extend(dep_values.iter().map(|v| format!("Ui.dep({v})")));
            seq.push(out);
            out = format!("({})", seq.join(", "));
        }
        out
    }

    /// `<Ctx.Provider value={v} key="k">children</Ctx.Provider>`.
    fn provider_text(&mut self, ctx: &str, e: &JSXElement<'_>) -> String {
        let at = e.opening_element.span.start;
        let mut value = None;
        let mut key = None;
        for item in &e.opening_element.attributes {
            let JSXAttributeItem::Attribute(a) = item else {
                self.fail(format!("line {}: spread on a provider", self.line(at)));
                return String::new();
            };
            let JSXAttributeName::Identifier(n) = &a.name else {
                self.fail(format!("line {}: namespaced attribute", self.line(at)));
                return String::new();
            };
            let v = self.attr_value(&a.value, at);
            match n.name.as_str() {
                "value" => value = Some(v),
                "key" => key = Some(v),
                other => self.fail(format!(
                    "line {}: a provider takes `value` and `key`, not `{other}`",
                    self.line(at)
                )),
            }
        }
        let Some(value) = value else {
            self.fail(format!(
                "line {}: a provider needs a `value`",
                self.line(at)
            ));
            return String::new();
        };
        let mut out = format!("Ui.provider({ctx}.id, {value})");
        if let Some(k) = key {
            out = format!("Ui.key({out}, {k})");
        }
        self.children_text(&mut out, &e.children, at);
        out
    }

    fn fragment_text(&mut self, f: &JSXFragment<'_>) -> String {
        let mut out = String::from("Ui.fragment()");
        self.children_text(&mut out, &f.children, f.span.start);
        out
    }
}

impl<'a> Visit<'a> for Finder<'_> {
    fn visit_jsx_element(&mut self, e: &JSXElement<'a>) {
        let text = self.element_text(e);
        self.edits.push(Edit {
            start: e.span.start as usize,
            end: e.span.end as usize,
            text,
        });
    }

    fn visit_jsx_fragment(&mut self, f: &JSXFragment<'a>) {
        let text = self.fragment_text(f);
        self.edits.push(Edit {
            start: f.span.start as usize,
            end: f.span.end as usize,
            text,
        });
    }

    fn visit_variable_declaration(&mut self, d: &VariableDeclaration<'a>) {
        // `const [a, setA] = useState(init);`
        if d.declarations.len() == 1
            && let decl = &d.declarations[0]
            && let BindingPattern::ArrayPattern(arr) = &decl.id
            && let Some(Expression::CallExpression(call)) = &decl.init
            && let Expression::Identifier(hook) = &call.callee
            && matches!(hook.name.as_str(), "useState" | "useReducer")
        {
            let (first, second) = if hook.name == "useState" {
                ("value", "set")
            } else {
                ("state", "dispatch")
            };
            let names: Vec<Option<String>> = arr
                .elements
                .iter()
                .map(|el| match el {
                    Some(BindingPattern::BindingIdentifier(b)) => Some(b.name.to_string()),
                    _ => None,
                })
                .collect();
            if arr.rest.is_some() || names.len() > 2 {
                self.fail(format!(
                    "line {}: useState returns [value, setter]",
                    self.line(d.span.start)
                ));
                return;
            }
            let tmp = format!("__st{}", d.span.start);
            // `useState(() => init)` and `useState(read)`: the function computes the first value.
            let lazy = hook.name == "useState"
                && match call.arguments.first().and_then(|a| a.as_expression()) {
                    Some(
                        Expression::ArrowFunctionExpression(_) | Expression::FunctionExpression(_),
                    ) => true,
                    Some(Expression::Identifier(id)) => {
                        self.declared_fns.contains(id.name.as_str())
                    }
                    _ => false,
                };
            let call_text = if lazy {
                format!(
                    "useStateLazy{}",
                    &self.src[hook.span.end as usize..call.span.end as usize]
                )
            } else {
                self.slice(call.span).to_string()
            };
            let mut text = format!("const {tmp} = {call_text};");
            if let Some(Some(v)) = names.first() {
                text += &format!(" const {v} = {tmp}.{first};");
            }
            if let Some(Some(s)) = names.get(1) {
                text += &format!(" const {s} = {tmp}.{second};");
                if hook.name == "useState" {
                    text += &format!(" const __up_{s} = {tmp}.update;");
                }
            }
            // The declaration's span may or may not include its `;`: the text ends with one either
            // way (a second one in the source is an empty statement).
            self.edits.push(Edit {
                start: d.span.start as usize,
                end: d.span.end as usize,
                text,
            });
            return;
        }
        walk::walk_variable_declaration(self, d);
    }

    fn visit_call_expression(&mut self, c: &CallExpression<'a>) {
        // `createRoot(target?).render(el)` hands the element to the host: `UiRoot.mount(target ?? 0, el)`.
        if let Expression::StaticMemberExpression(m) = &c.callee
            && m.property.name == "render"
            && let Expression::CallExpression(root) = &m.object
            && matches!(&root.callee, Expression::Identifier(f) if f.name == "createRoot")
            && let [el] = c.arguments.as_slice()
            && let Some(el) = el.as_expression()
        {
            let target = match root.arguments.first().and_then(|a| a.as_expression()) {
                Some(t) => self.slice(t.span()).to_string(),
                None => "0".to_string(),
            };
            let el = self.slice(el.span()).to_string();
            self.edits.push(Edit {
                start: c.span.start as usize,
                end: c.span.end as usize,
                text: format!("UiRoot.mount({target}, {el})"),
            });
            return;
        }
        // `useRef<HTMLElement>(null)` holds a node or nothing: `useRef<T | null>(null)`.
        if let Expression::Identifier(f) = &c.callee
            && f.name == "useRef"
            && let Some(ta) = &c.type_arguments
            && let [t] = ta.params.as_slice()
            && !self.slice(t.span()).contains("null")
            && matches!(
                c.arguments.first().and_then(|a| a.as_expression()),
                Some(Expression::NullLiteral(_))
            )
        {
            self.edits.push(Edit {
                start: t.span().end as usize,
                end: t.span().end as usize,
                text: " | null".into(),
            });
        }
        // `setN(n => n + 1)`: the updater form of a `useState` setter.
        if let Expression::Identifier(f) = &c.callee
            && self.setters.contains(f.name.as_str())
            && c.arguments.len() == 1
            && matches!(
                c.arguments[0].as_expression(),
                Some(Expression::ArrowFunctionExpression(_) | Expression::FunctionExpression(_))
            )
        {
            self.edits.push(Edit {
                start: f.span.start as usize,
                end: f.span.end as usize,
                text: format!("__up_{}", f.name),
            });
        }
        if let Expression::Identifier(f) = &c.callee
            && matches!(
                f.name.as_str(),
                "useEffect" | "useMemo" | "useCallback" | "useImperativeHandle"
            )
            && (c.arguments.len() == 2 || f.name == "useEffect" || c.arguments.len() == 3)
            && let Some(first) = c.arguments.first().and_then(|a| a.as_expression())
        {
            // `useImperativeHandle(ref, create, deps)` has its list third.
            let dep_at = if f.name == "useImperativeHandle" {
                2
            } else {
                1
            };
            if f.name == "useImperativeHandle" && c.arguments.len() < 3 {
                return;
            }
            let deps = match c.arguments.get(dep_at).and_then(|a| a.as_expression()) {
                Some(Expression::ArrayExpression(arr)) => {
                    let mut seq = vec!["Ui.depsBegin()".to_string()];
                    for el in &arr.elements {
                        match el.as_expression() {
                            Some(x) => seq.push(format!("Ui.dep({})", self.slice(x.span()))),
                            None => {
                                self.fail(format!(
                                    "line {}: a dependency list holds expressions",
                                    self.line(c.span.start)
                                ));
                                return;
                            }
                        }
                    }
                    Some(seq)
                }
                None => None,
                Some(_) => {
                    self.fail(format!(
                        "line {}: the dependencies must be an array literal",
                        self.line(c.span.start)
                    ));
                    return;
                }
            };
            let f_text = self.slice(first.span()).to_string();
            let call = if f.name == "useEffect" {
                format!("Ui.effect((): void => {{ Ui.runEffect({f_text}); }})")
            } else if f.name == "useImperativeHandle" {
                let second = c.arguments.get(1).and_then(|a| a.as_expression());
                let create = second.map_or("", |x| self.slice(x.span()));
                format!("useImperativeHandle({f_text}, {create})")
            } else {
                format!("{}({f_text})", f.name)
            };
            let text = match deps {
                Some(mut seq) => {
                    seq.push(call);
                    format!("({})", seq.join(", "))
                }
                None if f.name == "useEffect" => call,
                None => return,
            };
            self.edits.push(Edit {
                start: c.span.start as usize,
                end: c.span.end as usize,
                text,
            });
            return;
        }
        walk::walk_call_expression(self, c);
    }
}

/// The hook calls of one function body, in order.
#[derive(Default)]
struct HookScan(Vec<String>);

impl<'a> Visit<'a> for HookScan {
    fn visit_call_expression(&mut self, c: &CallExpression<'a>) {
        if let Expression::Identifier(f) = &c.callee {
            let n = f.name.as_str();
            if n.len() > 3 && n.starts_with("use") && n.as_bytes()[3].is_ascii_uppercase() {
                self.0.push(n.to_string());
            }
        }
        walk::walk_call_expression(self, c);
    }
}

/// `Name:ID:hook,hook;...` for every top-level component function (an uppercase name returning
/// `UiElement`): the id and the ordered hook list a hot reload compares to decide whether a
/// component keeps its state (same list) or starts over.
fn signatures(src: &str) -> Option<String> {
    let alloc = Allocator::default();
    let ret = Parser::new(&alloc, src, SourceType::tsx()).parse();
    if !ret.diagnostics.is_empty() {
        return None;
    }
    let mut out = Vec::new();
    for st in &ret.program.body {
        let f = match st {
            Statement::FunctionDeclaration(f) => &**f,
            Statement::ExportDeclaration(x) => match &x.declaration {
                Declaration::FunctionDeclaration(f) => &**f,
                _ => continue,
            },
            _ => continue,
        };
        let (Some(id), Some(body)) = (&f.id, &f.body) else {
            continue;
        };
        let name = id.name.as_str();
        let returns_element = f
            .return_type
            .as_ref()
            .is_some_and(|r| src[r.span.start as usize..r.span.end as usize].contains("UiElement"));
        if !name.as_bytes()[0].is_ascii_uppercase() || !returns_element {
            continue;
        }
        let mut scan = HookScan::default();
        scan.visit_function_body(body);
        out.push(format!(
            "{name}:{}:{}",
            component_id(name),
            scan.0.join(",")
        ));
    }
    (!out.is_empty()).then(|| out.join(";"))
}

/// The program with JSX and hooks rewritten, or `None` when it has none. A program with components
/// also exports `__uiSignatures()` (see `signatures`).
pub fn desugar(src: &str) -> R<Option<String>> {
    if !wanted(src) {
        return Ok(None);
    }
    let sig = signatures(src);
    let out = desugar_passes(src)?;
    Ok(match (out, sig) {
        (Some(text), Some(sig)) => Some(format!(
            "{text}\nexport function __uiSignatures(): string {{ return {}; }}\n",
            js_string(&sig)
        )),
        (None, Some(sig)) => Some(format!(
            "{src}\nexport function __uiSignatures(): string {{ return {}; }}\n",
            js_string(&sig)
        )),
        (out, None) => out,
    })
}

fn desugar_passes(src: &str) -> R<Option<String>> {
    let (mut cur, memo, forward) = prepass(src)?;
    let setters = setter_names(&cur);
    let (declared, declared_fns) = declared_names(&cur);
    let mut changed = cur != src;
    for _ in 0..64 {
        let alloc = Allocator::default();
        let ret = Parser::new(&alloc, &cur, SourceType::tsx()).parse();
        if !ret.diagnostics.is_empty() {
            // Plain TypeScript that is not TSX (`<T>x`) and merely mentions `</` is fine.
            let ts = Parser::new(&alloc, &cur, SourceType::ts()).parse();
            if ts.diagnostics.is_empty() {
                return Ok(if changed { Some(cur) } else { None });
            }
            // Otherwise it is a JSX error: report the TSX parser's, with its line in the user's
            // source (the passes keep the line count).
            let d = &ret.diagnostics[0];
            return Err(match d.labels.first() {
                Some(l) => {
                    let line = cur[..(l.offset() as usize).min(cur.len())]
                        .matches(char::from(10))
                        .count()
                        + 1;
                    format!("parse error (line {line}): {d}")
                }
                None => format!("parse error: {d}"),
            });
        }
        let mut finder = Finder {
            src: &cur,
            edits: Vec::new(),
            error: None,
            memo: memo.clone(),
            forward: forward.clone(),
            setters: setters.clone(),
            declared: declared.clone(),
            declared_fns: declared_fns.clone(),
        };
        finder.visit_program(&ret.program);
        if let Some(e) = finder.error {
            return Err(e);
        }
        let mut edits = finder.edits;
        if edits.is_empty() {
            return Ok(if changed { Some(cur) } else { None });
        }
        edits.sort_by_key(|e| e.start);
        let mut out = String::with_capacity(cur.len());
        let mut at = 0;
        for e in &edits {
            out.push_str(&cur[at..e.start]);
            out.push_str(&e.text);
            at = e.end;
        }
        out.push_str(&cur[at..]);
        // Keep the line count: the replacement holds the original's newlines.
        let lost = cur.matches('\n').count() as isize - out.matches('\n').count() as isize;
        if lost > 0 {
            out.push_str(&"\n".repeat(lost as usize));
        }
        cur = out;
        changed = true;
    }
    Err("JSX nests too deeply".into())
}

/// `const Fast = memo(Slow)` and `const Box = forwardRef((props, ref) => ...)` declarations: the
/// first is erased (the names are remembered), the second becomes a function taking the ref as its
/// second parameter. Returns the text and the two tables.
fn prepass(src: &str) -> R<(String, HashMap<String, String>, HashSet<String>)> {
    let mut memo = HashMap::new();
    let mut forward = HashSet::new();
    if !src.contains("memo(") && !src.contains("forwardRef(") {
        return Ok((src.to_string(), memo, forward));
    }
    let alloc = Allocator::default();
    let ret = Parser::new(&alloc, src, SourceType::tsx()).parse();
    if !ret.diagnostics.is_empty() {
        return Ok((src.to_string(), memo, forward));
    }
    let slice = |sp: oxc_span::Span| &src[sp.start as usize..sp.end as usize];
    let mut edits: Vec<Edit> = Vec::new();
    for st in &ret.program.body {
        let (decl, exported, span) = match st {
            Statement::VariableDeclaration(d) => (&**d, false, d.span),
            Statement::ExportDeclaration(x) => match &x.declaration {
                Declaration::VariableDeclaration(d) => (&**d, true, x.span),
                _ => continue,
            },
            _ => continue,
        };
        let [d] = decl.declarations.as_slice() else {
            continue;
        };
        let (BindingPattern::BindingIdentifier(id), Some(Expression::CallExpression(call))) =
            (&d.id, &d.init)
        else {
            continue;
        };
        let Expression::Identifier(f) = &call.callee else {
            continue;
        };
        let name = id.name.to_string();
        let arg = call.arguments.first().and_then(|a| a.as_expression());
        match (f.name.as_str(), arg) {
            ("memo", Some(Expression::Identifier(t))) => {
                memo.insert(name, t.name.to_string());
                let blank: String = slice(span)
                    .chars()
                    .map(|c| if c == '\n' { '\n' } else { ' ' })
                    .collect();
                edits.push(Edit {
                    start: span.start as usize,
                    end: span.end as usize,
                    text: blank,
                });
            }
            ("forwardRef", Some(arg)) => {
                let (params, ret_ty, body) = match arg {
                    Expression::ArrowFunctionExpression(a) => {
                        let body = match &a.body {
                            ArrowFunctionBody::FunctionBody(b) => slice(b.span).to_string(),
                            other => match other.as_expression() {
                                Some(e) => format!("{{ return {}; }}", slice(e.span())),
                                None => return Err("forwardRef: an empty arrow body".into()),
                            },
                        };
                        (&a.params, a.return_type.as_ref(), body)
                    }
                    Expression::FunctionExpression(f) => {
                        let Some(b) = &f.body else {
                            return Err("forwardRef: a function without a body".into());
                        };
                        (&f.params, f.return_type.as_ref(), slice(b.span).to_string())
                    }
                    _ => return Err("forwardRef takes a function".into()),
                };
                let plist: Vec<&str> = params.items.iter().map(|p| slice(p.span)).collect();
                if plist.len() != 2 {
                    return Err(format!(
                        "forwardRef({name}): the function takes (props, ref), not {} parameters",
                        plist.len()
                    ));
                }
                let ret = ret_ty.map_or("UiElement", |r| slice(r.type_annotation.span()));
                forward.insert(name.clone());
                edits.push(Edit {
                    start: span.start as usize,
                    end: span.end as usize,
                    text: format!(
                        "{}function {name}({}): {ret} {body}",
                        if exported { "export " } else { "" },
                        plist.join(", ")
                    ),
                });
            }
            _ => {}
        }
    }
    let mut out = String::with_capacity(src.len());
    let mut at = 0;
    for e in &edits {
        out.push_str(&src[at..e.start]);
        out.push_str(&e.text);
        at = e.end;
    }
    out.push_str(&src[at..]);
    Ok((out, memo, forward))
}

/// The names bound as the second element of `const [x, setX] = useState(..)`.
#[derive(Default)]
struct SetterScan(HashSet<String>);

impl<'a> Visit<'a> for SetterScan {
    fn visit_variable_declaration(&mut self, d: &VariableDeclaration<'a>) {
        for decl in &d.declarations {
            if let BindingPattern::ArrayPattern(arr) = &decl.id
                && let Some(Expression::CallExpression(call)) = &decl.init
                && matches!(&call.callee, Expression::Identifier(f) if f.name == "useState")
                && let Some(Some(BindingPattern::BindingIdentifier(b))) = arr.elements.get(1)
            {
                self.0.insert(b.name.to_string());
            }
        }
        walk::walk_variable_declaration(self, d);
    }
}

/// Names the program declares at its top level (functions, classes, variables).
fn declared_names(src: &str) -> (HashSet<String>, HashSet<String>) {
    let alloc = Allocator::default();
    let ret = Parser::new(&alloc, src, SourceType::tsx()).parse();
    let mut out = HashSet::new();
    let mut fns = HashSet::new();
    if !ret.diagnostics.is_empty() {
        return (out, fns);
    }
    fn vars(out: &mut HashSet<String>, fns: &mut HashSet<String>, v: &VariableDeclaration<'_>) {
        for d in &v.declarations {
            if let BindingPattern::BindingIdentifier(id) = &d.id {
                out.insert(id.name.to_string());
                if matches!(
                    &d.init,
                    Some(
                        Expression::ArrowFunctionExpression(_) | Expression::FunctionExpression(_)
                    )
                ) {
                    fns.insert(id.name.to_string());
                }
            }
        }
    }
    for st in &ret.program.body {
        match st {
            Statement::FunctionDeclaration(f) => {
                out.extend(f.id.as_ref().map(|i| i.name.to_string()));
                fns.extend(f.id.as_ref().map(|i| i.name.to_string()));
            }
            Statement::ClassDeclaration(c) => {
                out.extend(c.id.as_ref().map(|i| i.name.to_string()));
            }
            Statement::VariableDeclaration(v) => vars(&mut out, &mut fns, v),
            Statement::ExportDeclaration(x) => match &x.declaration {
                Declaration::FunctionDeclaration(f) => {
                    out.extend(f.id.as_ref().map(|i| i.name.to_string()));
                    fns.extend(f.id.as_ref().map(|i| i.name.to_string()));
                }
                Declaration::ClassDeclaration(c) => {
                    out.extend(c.id.as_ref().map(|i| i.name.to_string()));
                }
                Declaration::VariableDeclaration(v) => vars(&mut out, &mut fns, v),
                _ => {}
            },
            _ => {}
        }
    }
    // Functions anywhere in the program: `useState(read)` with a local `const read = () => ..`.
    let mut all = AllFns(HashSet::new());
    all.visit_program(&ret.program);
    fns.extend(all.0);
    (out, fns)
}

/// Names bound to a function expression, an arrow or a function declaration, at any depth.
struct AllFns(HashSet<String>);

impl<'a> Visit<'a> for AllFns {
    fn visit_variable_declarator(&mut self, d: &VariableDeclarator<'a>) {
        if let BindingPattern::BindingIdentifier(id) = &d.id
            && matches!(
                &d.init,
                Some(Expression::ArrowFunctionExpression(_) | Expression::FunctionExpression(_))
            )
        {
            self.0.insert(id.name.to_string());
        }
        walk::walk_variable_declarator(self, d);
    }
    fn visit_function(&mut self, f: &Function<'a>, flags: oxc_syntax::scope::ScopeFlags) {
        if let Some(id) = &f.id {
            self.0.insert(id.name.to_string());
        }
        walk::walk_function(self, f, flags);
    }
}

fn setter_names(src: &str) -> HashSet<String> {
    let alloc = Allocator::default();
    let ret = Parser::new(&alloc, src, SourceType::tsx()).parse();
    let mut scan = SetterScan::default();
    if ret.diagnostics.is_empty() {
        scan.visit_program(&ret.program);
    }
    scan.0
}
