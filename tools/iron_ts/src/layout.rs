//! Rust bindings generated from the IR: `#[repr(C)]` structs with the exact layouts the
//! generated code uses, string-literal tag constants, and `extern "C"` declarations of the
//! exported functions. A host links the object file and includes this text.

use crate::ir::*;

fn ident(s: &str) -> String {
    let id: String = s
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    match id.as_str() {
        "type" | "match" | "fn" | "use" | "mod" | "loop" | "ref" | "self" | "in" | "as" => {
            format!("r#{id}")
        }
        _ => id,
    }
}

fn struct_name(m: &Module, id: StructId) -> String {
    // Generated class names (`Generator$number`) are not Rust identifiers.
    let clean = |n: &str| n.replace('$', "_");
    let n = clean(&m.structs[id].name);
    // Names can repeat (anonymous shapes): add the id only for the later ones.
    if m.structs[..id].iter().any(|s| clean(&s.name) == n) {
        format!("{n}{id}")
    } else {
        n
    }
}

fn rust_ty(m: &Module, t: &Ty, in_struct: bool) -> String {
    match t {
        Ty::Num | Ty::Nullable(_) if t.strip() == &Ty::Num => "f64".into(),
        // Slots are 8 bytes wide: small values are stored zero-extended.
        Ty::Bool | Ty::Lit if in_struct => "u64".into(),
        Ty::Bool => "bool".into(),
        Ty::Lit => "u32".into(),
        Ty::Void => "()".into(),
        other => match other.strip() {
            Ty::Obj(s) => format!("*mut {}", struct_name(m, *s)),
            Ty::Handle(_) => "u64".into(),
            Ty::Arr(_) | Ty::Typed(_) => "*mut Array".into(),
            Ty::Fn(_) => "*mut Closure".into(),
            _ => "*mut u8".into(),
        },
    }
}

/// The type of a `@property` field, as a short name a host can switch on.
fn prop_kind(m: &Module, t: &Ty) -> String {
    let base = match t.strip() {
        Ty::Num => "number".to_string(),
        Ty::Bool => "boolean".to_string(),
        Ty::Lit => "literal".to_string(),
        Ty::Str => "string".to_string(),
        Ty::Obj(s) => format!("object:{}", struct_name(m, *s)),
        Ty::Arr(_) | Ty::Typed(_) => "array".to_string(),
        Ty::Fn(_) => "function".to_string(),
        _ => "other".to_string(),
    };
    if t.is_nullable() {
        format!("{base}?")
    } else {
        base
    }
}

pub fn rust_bindings(m: &Module) -> String {
    let mut s = String::new();
    s += "// Generated by iron_ts. Do not edit.\nuse iron_ts_rt::{Array, Closure};\n\n";
    s += &format!("pub const NULL_NUM_BITS: u64 = {NULL_NUM_BITS:#x};\n");
    s += "/// A `number | null` slot is null when its bits equal this.\npub fn is_null_num(v: f64) -> bool { v.to_bits() == NULL_NUM_BITS }\n";
    s += "pub fn null_num() -> f64 { f64::from_bits(NULL_NUM_BITS) }\n\n";
    // A tag is only a constant if its text makes a distinct identifier (string literals used as
    // `string` values also become tags: `","` and `")"` would both be `TAG__`).
    let mut seen = std::collections::HashSet::new();
    for (i, t) in m.tags.iter().enumerate() {
        let id = ident(t);
        if t.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') && seen.insert(id.clone()) {
            s += &format!("pub const TAG_{id}: u32 = {i};\n");
        }
    }
    s += "\n";
    for (id, st) in m.structs.iter().enumerate() {
        s += &format!(
            "/// Struct id {id}: the header word of its objects, for `ts_rt_obj_new`.\npub const HDR_{}: u64 = {};\n#[repr(C)]\n#[derive(Debug)]\npub struct {} {{\n    pub header: u64,\n",
            struct_name(m, id),
            m.struct_base as usize + id + 1,
            struct_name(m, id)
        );
        for f in &st.fields {
            s += &format!("    pub {}: {},\n", ident(&f.name), rust_ty(m, &f.ty, true));
        }
        s += "}\n\n";
    }
    for t in &m.props {
        s += &format!(
            "/// The `@property` fields of {0}: name, byte offset in the object, type.\npub const PROPS_{0}: &[(&str, usize, &str)] = &[\n",
            struct_name(m, t.class)
        );
        for e in &t.entries {
            s += &format!(
                "    (\"{}\", {}, \"{}\"),\n",
                e.name,
                field_offset(e.index),
                prop_kind(m, &e.ty)
            );
        }
        s += "];\n\n";
    }
    s += "unsafe extern \"C\" {\n";
    for f in &m.funcs {
        if !f.exported {
            continue;
        }
        let params: Vec<String> = f
            .params
            .iter()
            .map(|p| format!("p{p}: {}", rust_ty(m, &f.locals[*p as usize], false)))
            .collect();
        let ret = if f.ret == Ty::Void {
            String::new()
        } else {
            format!(" -> {}", rust_ty(m, &f.ret, false))
        };
        s += &format!(
            "    pub fn ts_{}{}({}){};\n",
            m.prefix,
            f.name,
            params.join(", "),
            ret
        );
    }
    s += "}\n";
    s += &component_table(m);
    s
}

/// The class table of `register(Class)`: wrappers that erase the object type, and `classes()`.
/// Built from the exports `components.rs` generated (`iron_new_X`, `iron_hook_X_onUpdate`).
fn component_table(m: &Module) -> String {
    const HOOKS: [&str; 7] = [
        "onAwake",
        "onStart",
        "onUpdate",
        "onLateUpdate",
        "onFixedUpdate",
        "onPreRender",
        "onDestroy",
    ];
    let mut out = String::new();
    let mut entries = Vec::new();
    for f in m.funcs.iter().filter(|f| f.exported) {
        let Some(class) = f.name.strip_prefix("iron_new_") else {
            continue;
        };
        let sym = format!("ts_{}{}", m.prefix, f.name);
        let has_go = f.params.len() > 1;
        let (go_param, go_arg) = if has_go {
            (", go: u64", ", go")
        } else {
            ("", "")
        };
        out += &format!(
            "unsafe extern \"C\" fn create_{class}(id: f64{go_param}) -> *mut u8 {{ unsafe {{ {sym}(id{go_arg}) as *mut u8 }} }}\n"
        );
        let mut hooks = Vec::new();
        for h in HOOKS {
            let name = format!("iron_hook_{class}_{h}");
            if let Some(hf) = m.funcs.iter().find(|g| g.exported && g.name == name) {
                let hs = format!("ts_{}{}", m.prefix, hf.name);
                let ty = rust_ty(m, &hf.locals[hf.params[0] as usize], false);
                out += &format!(
                    "unsafe extern \"C\" fn hook_{class}_{h}(c: *mut u8, dt: f64) {{ unsafe {{ {hs}(c as {ty}, dt) }} }}\n"
                );
                hooks.push(format!(
                    "Some(hook_{class}_{h} as unsafe extern \"C\" fn(*mut u8, f64))"
                ));
            } else {
                hooks.push("None".to_string());
            }
        }
        // `create` has one signature in the table: (id, object).
        out += &format!(
            "unsafe extern \"C\" fn create_{class}_any(id: f64, go: u64) -> *mut u8 {{ {} }}\n",
            if has_go {
                format!("unsafe {{ create_{class}(id, go) }}")
            } else {
                format!("{{ let _ = go; unsafe {{ create_{class}(id) }} }}")
            }
        );
        entries.push(format!(
            "        iron_ts_rt::NativeClass {{ name: \"{class}\", create: create_{class}_any, hooks: [{}] }},\n",
            hooks.join(", ")
        ));
    }
    if entries.is_empty() {
        return out;
    }
    out += "/// The classes the program registered, for `iron_ts_rt::NativeHost`.\npub fn classes() -> Vec<iron_ts_rt::NativeClass> {\n    vec![\n";
    for e in entries {
        out += &e;
    }
    out += "    ]\n}\n";
    out
}
