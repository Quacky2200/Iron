//! Rust bindings generated from the IR: `#[repr(C)]` structs with the exact layouts the
//! generated code uses, string-literal tag constants, and `extern "C"` declarations of the
//! exported functions. A host links the object file and includes this text.

use crate::ir::*;

fn ident(s: &str) -> String {
    let id: String = s
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    match id.as_str() {
        "type" | "match" | "fn" | "use" | "mod" | "loop" | "ref" | "self" | "in" | "as" => {
            format!("r#{id}")
        }
        _ => id,
    }
}

fn struct_name(m: &Module, id: StructId) -> String {
    let n = &m.structs[id].name;
    // Names can repeat (anonymous shapes): add the id only for the later ones.
    if m.structs[..id].iter().any(|s| s.name == *n) {
        format!("{n}{id}")
    } else {
        n.clone()
    }
}

fn rust_ty(m: &Module, t: &Ty, in_struct: bool) -> String {
    match t {
        Ty::Num | Ty::Nullable(_) if t.strip() == &Ty::Num => "f64".into(),
        // Slots are 8 bytes wide: small values are stored zero-extended.
        Ty::Bool | Ty::Lit if in_struct => "u64".into(),
        Ty::Bool => "bool".into(),
        Ty::Lit => "u32".into(),
        Ty::Void => "()".into(),
        other => match other.strip() {
            Ty::Obj(s) => format!("*mut {}", struct_name(m, *s)),
            Ty::Arr(_) | Ty::Bytes => "*mut Array".into(),
            Ty::Fn(_) => "*mut Closure".into(),
            _ => "*mut u8".into(),
        },
    }
}

pub fn rust_bindings(m: &Module) -> String {
    let mut s = String::new();
    s += "// Generated by iron_ts. Do not edit.\nuse iron_ts_rt::{Array, Closure};\n\n";
    s += &format!("pub const NULL_NUM_BITS: u64 = {NULL_NUM_BITS:#x};\n");
    s += "/// A `number | null` slot is null when its bits equal this.\npub fn is_null_num(v: f64) -> bool { v.to_bits() == NULL_NUM_BITS }\n";
    s += "pub fn null_num() -> f64 { f64::from_bits(NULL_NUM_BITS) }\n\n";
    for (i, t) in m.tags.iter().enumerate() {
        s += &format!("pub const TAG_{}: u32 = {i};\n", ident(t));
    }
    s += "\n";
    for (id, st) in m.structs.iter().enumerate() {
        s += &format!(
            "/// Struct id {id}; the header word holds {}.\n#[repr(C)]\n#[derive(Debug)]\npub struct {} {{\n    pub header: u64,\n",
            id + 1,
            struct_name(m, id)
        );
        for f in &st.fields {
            s += &format!("    pub {}: {},\n", ident(&f.name), rust_ty(m, &f.ty, true));
        }
        s += "}\n\n";
    }
    s += "unsafe extern \"C\" {\n";
    for f in &m.funcs {
        if !f.exported {
            continue;
        }
        let params: Vec<String> = f
            .params
            .iter()
            .map(|p| format!("p{p}: {}", rust_ty(m, &f.locals[*p as usize], false)))
            .collect();
        let ret = if f.ret == Ty::Void {
            String::new()
        } else {
            format!(" -> {}", rust_ty(m, &f.ret, false))
        };
        s += &format!("    pub fn ts_{}({}){};\n", f.name, params.join(", "), ret);
    }
    s += "}\n";
    s
}
