// Bundles the docs into the reader: every Markdown file goes into src/docs.gen.ts, and the
// images they can show (anything but video) are copied into content/, inside the game
// folder, where `image` elements can load them. Both outputs are git-ignored; `bun run
// build` runs this.
//
// By default that's Platypus's own docs: `docs/` and the repository's top-level `.md` files.
// `--root <folder>` (or `MD_READER_ROOT`) bundles every `.md` under another folder instead,
// with paths relative to it.
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, extname, join, relative, resolve } from "node:path";

const here = import.meta.dir;
const repo = join(here, "../..");
const IMAGES = new Set([".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp", ".bmp", ".ico", ".avif"]);
// Folders a docs tree never needs.
const SKIP = new Set(["node_modules", ".git", "dist", "target", ".platypus"]);

const flag = process.argv.indexOf("--root");
const rootArg = flag >= 0 ? process.argv[flag + 1] : process.env.MD_READER_ROOT;
const root = rootArg ? resolve(process.cwd(), rootArg) : repo;

const docs: Record<string, string> = {};
const images: string[] = [];

function walk(dir: string) {
  for (const name of readdirSync(dir).sort()) {
    const file = join(dir, name);
    if (statSync(file).isDirectory()) {
      // Not this reader's own image copies, when the root holds the reader.
      if (!SKIP.has(name) && file !== join(here, "content")) walk(file);
    } else visit(file);
  }
}

function visit(file: string) {
  const path = relative(root, file).replaceAll("\\", "/");
  const ext = extname(file).toLowerCase();
  if (ext === ".md") docs[path] = readFileSync(file, "utf8").replaceAll("\r\n", "\n");
  else if (IMAGES.has(ext)) images.push(path);
}

if (rootArg) {
  if (!statSync(root, { throwIfNoEntry: false })?.isDirectory()) throw new Error(`--root: ${root} is not a folder`);
  walk(root);
} else {
  for (const name of readdirSync(repo).sort()) {
    if (name.toLowerCase().endsWith(".md") && statSync(join(repo, name)).isFile()) visit(join(repo, name));
  }
  walk(join(repo, "docs"));
}

rmSync(join(here, "content"), { recursive: true, force: true });
for (const path of images) {
  const to = join(here, "content", path);
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(join(root, path), to);
}

// Shown first in the path bar.
const rootInfo = { name: rootArg ? basename(root) : "Platypus" };
writeFileSync(
  join(here, "src/docs.gen.ts"),
  "// Generated by gen-docs.ts: do not edit.\n" +
    `export const ROOT: { name: string } = ${JSON.stringify(rootInfo)};\n` +
    `export const DOCS: Record<string, string> = ${JSON.stringify(docs)};\n` +
    `export const IMAGES: string[] = ${JSON.stringify(images)};\n`,
);
console.log(`md-reader: ${Object.keys(docs).length} docs, ${images.length} images from ${rootArg ? root : "Platypus's docs"}`);
