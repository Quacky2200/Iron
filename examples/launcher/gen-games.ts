// Lists the examples for the launcher: each one's folder, title and description (from its
// package.json) go into src/games.gen.ts, and its screenshot from `bun run screenshots`
// (tests/output/examples-<name>.png) is copied into content/shots/, where `image` elements
// can load it. Both outputs are git-ignored; `bun run build` runs this.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const here = import.meta.dir;
const examples = join(here, "..");
const shots = join(here, "../../tests/output");

interface Game {
  name: string;
  title: string;
  description: string;
  shot: string | null;
}

/** "Iron - God rays: the cell" → "God rays: the cell"; no title → "Sine circle demo". */
function title(name: string, given: unknown): string {
  if (typeof given === "string" && given.trim()) return given.replace(/^Iron\s*[-—–]\s*/, "").trim();
  const words = name.replaceAll("-", " ");
  return words[0]!.toUpperCase() + words.slice(1);
}

rmSync(join(here, "content"), { recursive: true, force: true });
mkdirSync(join(here, "content/shots"), { recursive: true });

const games: Game[] = [];
for (const name of readdirSync(examples).sort()) {
  const manifest = join(examples, name, "package.json");
  if (name === basename(here) || !existsSync(manifest)) continue;
  const pkg = JSON.parse(readFileSync(manifest, "utf8"));
  const from = join(shots, `examples-${name}.png`);
  let shot: string | null = null;
  if (existsSync(from)) {
    shot = `content/shots/${name}.png`;
    copyFileSync(from, join(here, shot));
  }
  games.push({ name, title: title(name, pkg.iron?.title), description: pkg.description ?? "", shot });
}

writeFileSync(
  join(here, "src/games.gen.ts"),
  "// Generated by gen-games.ts: do not edit.\n" +
    "export interface Game { name: string; title: string; description: string; shot: string | null }\n" +
    `export const GAMES: Game[] = ${JSON.stringify(games, null, 2)};\n`,
);
const missing = games.filter((g) => !g.shot).map((g) => g.name);
console.log(`launcher: ${games.length} games, ${games.length - missing.length} screenshots`);
if (missing.length) console.log(`  no screenshot (bun run screenshots ${missing.join(" ")}): ${missing.join(", ")}`);
