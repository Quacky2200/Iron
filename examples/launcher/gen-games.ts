// Lists the examples for the launcher: each one's folder, title and description (from its
// project.json) go into src/games.gen.ts, and its screenshot from the `screenshots` tool (tests/tools/shots)
// (tests/output/examples-<name>.png) is copied into content/shots/, where `image` elements
// can load it, and its colours (palette.ts) give it a background gradient. Both outputs are
// git-ignored; `bun run build` runs this.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

import { fallback, type Palette, palette } from "./palette.ts";

const here = import.meta.dir;
const examples = join(here, "..");
const shots = join(here, "../../tests/output");

interface Game {
  name: string;
  title: string;
  description: string;
  shot: string | null;
  palette: Palette;
}

/** "Platypus - God rays: the cell" → "God rays: the cell"; no title → "Sine circle demo". */
function title(name: string, given: unknown): string {
  if (typeof given === "string" && given.trim()) return given.replace(/^Platypus\s*[-—–]\s*/, "").trim();
  const words = name.replaceAll("-", " ");
  return words[0]!.toUpperCase() + words.slice(1);
}

rmSync(join(here, "content"), { recursive: true, force: true });
mkdirSync(join(here, "content/shots"), { recursive: true });

const games: Game[] = [];
for (const name of readdirSync(examples).sort()) {
  const manifest = join(examples, name, "project.json");
  if (name === basename(here) || !existsSync(manifest)) continue;
  const pkg = JSON.parse(readFileSync(manifest, "utf8"));
  const from = join(shots, `examples-${name}.png`);
  let shot: string | null = null;
  let colors: Palette | null = null;
  if (existsSync(from)) {
    shot = `content/shots/${name}.png`;
    copyFileSync(from, join(here, shot));
    colors = palette(readFileSync(from));
  }
  games.push({
    name,
    title: title(name, pkg.title),
    description: pkg.description ?? "",
    shot,
    palette: colors ?? fallback(name),
  });
}

writeFileSync(
  join(here, "src/games.gen.ts"),
  "// Generated by gen-games.ts: do not edit.\n" +
    "export interface Palette { top: string; bottom: string; glow: string; picture: number }\n" +
    "export interface Game { name: string; title: string; description: string; shot: string | null; palette: Palette }\n" +
    `export const GAMES: Game[] = ${JSON.stringify(games, null, 2)};\n`,
);
const missing = games.filter((g) => !g.shot).map((g) => g.name);
console.log(`launcher: ${games.length} games, ${games.length - missing.length} screenshots`);
if (missing.length) console.log(`  no screenshot (cd tools && cargo run -p platypus_shots --bin screenshots -- ${missing.join(" ")}): ${missing.join(", ")}`);
