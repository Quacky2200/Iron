//! The data side of rendering for scripts: `js/engine/src/rendering.ts`, `textures.ts`,
//! `models.ts`, `particles.ts`, `lines.ts`, `cloth.ts`, `primitives.ts` and `cursor.ts` as
//! `#[platypus_api]` classes over per-thread registries. Nothing here draws: the app reads the
//! registries (`lights()`, `mesh_renderers()`, `texture_info(..)`, ...) and the command queue
//! ([`take_commands`]) and feeds the renderer. Components are engine components like `Camera`
//! (static `attach` / `findOn`, so `go.addComponent(Light, { .. })` works) with scene-file kinds
//! ([`register_kinds`]); assets (`Texture`, `Mesh`, `Material`, `Sprite`) are handles with asset
//! kinds, so scene files with `assets` tables and `Material` values load and save.
//!
//! The plain components are generated by `build.rs` from `gen/components.rs` into `generated.rs`.
//! Design: `docs/research/platypus-native-engine.md`; usage: `docs/platypus-api.md`.

