// ---- JSON values the kinds read ----

fn numbers(v: &Value) -> Option<Vec<f64>> {
    let a = v.get("value").unwrap_or(v).as_array()?;
    a.iter().map(Value::as_f64).collect()
}

pub(crate) fn color_of(v: &Value) -> Option<Rgba> {
    let n = numbers(v)?;
    (n.len() == 4).then(|| Rgba {
        r: n[0],
        g: n[1],
        b: n[2],
        a: n[3],
    })
}

pub(crate) fn v2_of(v: &Value) -> Option<V2> {
    let n = numbers(v)?;
    (n.len() == 2).then(|| V2 { x: n[0], y: n[1] })
}

pub(crate) fn v3_of(v: &Value) -> Option<V3> {
    let n = numbers(v)?;
    (n.len() == 3).then(|| V3 {
        x: n[0],
        y: n[1],
        z: n[2],
    })
}

pub(crate) fn rect_of(v: &Value) -> Option<[f64; 4]> {
    let n = numbers(v)?;
    (n.len() == 4).then(|| [n[0], n[1], n[2], n[3]])
}

/// A GameObject placeholder (`None` for null).
pub(crate) fn object_of(v: &Value) -> Option<Option<ObjectId>> {
    match v {
        Value::Null => Some(None),
        Value::Object(o) if o.get("$ref").and_then(Value::as_str) == Some("GameObject") => {
            let raw = o.get("object")?.as_u64()?;
            Some(Some(ObjectId::from_raw(raw)))
        }
        _ => None,
    }
}

/// A mesh property: a built-in primitive is its name, any other mesh an asset placeholder.
pub(crate) fn mesh_value(mesh: u32) -> Value {
    let mesh = cloth_source(mesh).unwrap_or(mesh);
    if let Some(name) = primitive_name(MeshRef(mesh)) {
        return json!(name);
    }
    asset_ref("Mesh", u64::from(mesh))
}

pub(crate) fn mesh_of(v: &Value) -> Option<u32> {
    match v {
        Value::String(name) => Some(primitive_mesh(name).0),
        other => asset_handle(other, "Mesh").map(|h| h as u32),
    }
}

/// Removes the data components of destroyed objects (call it with
/// `platypus_engine_api::objects::process_destroyed`'s list).
pub fn destroyed(objects: &[ObjectId]) {
    for o in objects {
        remove_generated_on(*o);
    }
    models::forget_objects(objects);
}

/// Forgets every render component, asset and queued command (a test, or a reload).
pub fn reset() {
    reset_generated();
    reset_resources();
    render_settings::reset_render_settings();
    effects::reset_effects();
    models::reset_models();
    visibility::reset_visibility();
}

/// The manifests of this crate's script API, for the compiler.
pub fn manifests() -> Vec<String> {
    let mut all = generated_manifests();
    all.extend(resources::resource_manifests());
    all.push(render_settings::render_settings_api::MANIFEST.to_json());
    all.push(render_settings::render_stats_api::MANIFEST.to_json());
    all.push(render_settings::graphics_settings_api::MANIFEST.to_json());
    all.extend(effects::effect_manifests());
    all.extend(models::model_manifests());
    all
}

/// Registers the scene-file kinds and asset kinds on this thread.
pub fn register_kinds() {
    register_generated_kinds();
    register_resource_kinds();
    models::register_model_extra();
}

