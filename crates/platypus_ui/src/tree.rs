/// Evaluates a `content` value: quoted strings and `attr(name)`, concatenated.
/// `none` and `normal` mean no generated content.
fn parse_content(value: &str, attrs: Option<&Attrs>) -> Option<String> {
    let value = value.trim();
    if value == "none" || value == "normal" {
        return None;
    }
    let mut out = String::new();
    let mut chars = value.char_indices().peekable();
    while let Some((i, c)) = chars.next() {
        match c {
            '"' | '\'' => {
                let quote = c;
                while let Some((j, c)) = chars.next() {
                    match c {
                        '\\' => {
                            let (escaped, used) = css_escape(&value[j + 1..]);
                            out.extend(escaped);
                            let end = j + 1 + used;
                            while chars.next_if(|(k, _)| *k < end).is_some() {}
                        }
                        c if c == quote => break,
                        c => out.push(c),
                    }
                }
            }
            _ if value[i..].starts_with("attr(") => {
                let rest = &value[i + 5..];
                let end = rest.find(')')?;
                let name = rest[..end].trim();
                if let Some(v) = attrs.and_then(|a| a.get(name)) {
                    out.push_str(v);
                }
                // Skip past the closing paren.
                let skip = 5 + end;
                for _ in 0..skip {
                    chars.next();
                }
            }
            _ => {}
        }
    }
    Some(out)
}

/// The selector keys that differ between two attribute sets.
/// Without a restyle pass, `dir` fills in `direction` when no inline style sets it.
fn dir_fallback(node: &mut Node) {
    if !node.inline.iter().any(|(p, _)| p == "direction") {
        node.visual.text.direction = node.attrs.dir;
    }
}

fn attr_keys_changed(before: &Attrs, after: &Attrs) -> Vec<Key> {
    let mut keys = Vec::new();
    for c in before.classes.iter().filter(|c| !after.classes.contains(c)) {
        keys.push(Key::Class(c.clone()));
    }
    for c in after.classes.iter().filter(|c| !before.classes.contains(c)) {
        keys.push(Key::Class(c.clone()));
    }
    if before.classes != after.classes {
        keys.push(Key::Attr("class".into()));
    }
    if before.id != after.id {
        keys.extend(
            before
                .id
                .iter()
                .chain(after.id.iter())
                .map(|i| Key::Id(i.clone())),
        );
        keys.push(Key::Attr("id".into()));
    }
    if before.disabled != after.disabled {
        keys.push(Key::Disabled);
    }
    if before.checked != after.checked {
        keys.push(Key::Checked);
    }
    if before.dir != after.dir {
        keys.push(Key::Attr("dir".into()));
    }
    if before.input_type != after.input_type {
        keys.push(Key::Attr("type".into()));
    }
    if before.title != after.title {
        keys.push(Key::Attr("title".into()));
    }
    if before.open != after.open {
        keys.push(Key::Attr("open".into()));
    }
    if before.modal != after.modal {
        keys.push(Key::Attr("modal".into()));
    }
    for (name, value) in before.data.iter().chain(after.data.iter()) {
        let _ = value;
        if before.get(name) != after.get(name) {
            keys.push(Key::Attr(name.clone()));
        }
    }
    keys.dedup();
    keys
}
