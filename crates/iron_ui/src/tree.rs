/// Element type of text nodes created with `CREATE_TEXT`.
pub const TEXT_NODE: &str = "#text";

/// Element types whose children are inline content laid out by the text engine.
fn is_inline_container(kind: &str) -> bool {
    matches!(kind, "text" | "span")
}

/// The background layers to paint over the box, bottom first, and the topmost
/// `background-clip: text` gradient (painted inside the text instead).
fn background_layers(
    v: &Visual,
    rect: Rect,
    radii: Radii,
    l: &NodeLayout,
    pixelated: bool,
) -> (Vec<ImageFill>, Option<Arc<BackgroundImage>>) {
    let mut fills = Vec::new();
    let mut text_fill = None;
    for (i, image) in v.background_images.iter().enumerate().rev() {
        let Some(image) = image else {
            continue;
        };
        let pick = |n: usize| i % n;
        let clip = v.background_clips[pick(v.background_clips.len())];
        if clip == BackgroundClip::Text {
            if !matches!(**image, BackgroundImage::Url(_)) {
                text_fill = Some(image.clone());
            }
            continue;
        }
        let (area, area_radii) = clip_area(clip, rect, radii, l);
        fills.push(ImageFill {
            image: image.clone(),
            size: v.background_sizes[pick(v.background_sizes.len())],
            position: v.background_positions[pick(v.background_positions.len())],
            repeat: v.background_repeats[pick(v.background_repeats.len())],
            area,
            radii: area_radii,
            pixelated,
        });
    }
    (fills, text_fill)
}

/// The element's outline: a border around the border box grown by `outlineOffset`,
/// following the corner radii, drawn over the element's content.
fn outline(v: &Visual, rect: Rect, radii: Radii, text_color: Rgba) -> Option<DrawCmd> {
    let color = if v.outline_current {
        text_color
    } else {
        v.outline_color
    };
    let w = v.outline_width;
    if !v.outline_style.is_visible() || w <= 0.0 || color.a <= 0.0 {
        return None;
    }
    let grow = v.outline_offset + w;
    let area = rect.expand(grow);
    if area.is_empty() {
        return None;
    }
    Some(DrawCmd::Border {
        rect: area,
        radii: radii.grow(grow),
        widths: [w; 4],
        colors: [color; 4],
        styles: [v.outline_style; 4],
    })
}

/// A box whose background layers blend with each other (`background-blend-mode`):
/// an isolated group holding the colour, then each layer bottom first (blended ones
/// in their own layer), then the border.
fn blended_background(quad: Quad, v: &Visual, out: &mut Vec<DrawCmd>) {
    let layer = |blend| DrawCmd::PushLayer {
        bounds: quad.rect,
        blur: 0.0,
        opacity: 1.0,
        blend,
        matrix: None,
        shadows: Vec::new(),
    };
    out.push(layer(BlendMode::Normal));
    out.push(DrawCmd::Quad(Quad {
        images: Vec::new(),
        border_color: Rgba::TRANSPARENT,
        ..quad.clone()
    }));
    // `quad.images` is bottom first; blend modes are listed top first.
    let count = v.background_images.len();
    let mut images = quad.images.iter();
    for (i, image) in v.background_images.iter().enumerate().rev() {
        let clip = v.background_clips[i % v.background_clips.len()];
        if image.is_none() || clip == BackgroundClip::Text {
            continue;
        }
        let Some(fill) = images.next() else {
            break;
        };
        let blend = v.background_blends[i % v.background_blends.len()];
        let single = DrawCmd::Quad(Quad {
            background: Rgba::TRANSPARENT,
            images: vec![fill.clone()],
            border_color: Rgba::TRANSPARENT,
            ..quad.clone()
        });
        // The bottom layer blends with the colour too, like CSS.
        if blend == BlendMode::Normal || (i + 1 == count && quad.background.a <= 0.0) {
            out.push(single);
        } else {
            out.push(layer(blend));
            out.push(single);
            out.push(DrawCmd::PopLayer);
        }
    }
    out.push(DrawCmd::Quad(Quad {
        background: Rgba::TRANSPARENT,
        images: Vec::new(),
        ..quad
    }));
    out.push(DrawCmd::PopLayer);
}

/// The mask layers, bottom first, over the border box (`mask-clip` and
/// `mask-origin` are `border-box`). One mode applies to all of them: the top
/// layer's.
fn mask_layers(v: &Visual, rect: Rect, pixelated: bool) -> Vec<ImageFill> {
    v.mask_images
        .iter()
        .enumerate()
        .rev()
        .filter_map(|(i, image)| {
            Some(ImageFill {
                image: image.clone()?,
                size: v.mask_sizes[i % v.mask_sizes.len()],
                position: v.mask_positions[i % v.mask_positions.len()],
                repeat: v.mask_repeats[i % v.mask_repeats.len()],
                area: rect,
                radii: Radii::ZERO,
                pixelated,
            })
        })
        .collect()
}

/// The `background-clip` box and its corner radii (the outer radii shrunk by the inset).
fn clip_area(clip: BackgroundClip, rect: Rect, radii: Radii, l: &NodeLayout) -> (Rect, Radii) {
    let inset = match clip {
        BackgroundClip::BorderBox | BackgroundClip::Text => [0.0; 4],
        BackgroundClip::PaddingBox => l.border,
        BackgroundClip::ContentBox => [0, 1, 2, 3].map(|i| l.border[i] + l.padding[i]),
    };
    let [t, r, b, left] = inset;
    let area = Rect::new(
        rect.x + left,
        rect.y + t,
        (rect.width - left - r).max(0.0),
        (rect.height - t - b).max(0.0),
    );
    (area, radii.inner(inset))
}

/// The element type of images.
const IMAGE: &str = "image";

/// The element type of lists: their element children are list items.
const LIST: &str = "list";

/// An element's style before any declarations (the user-agent styles): lists are
/// columns with room on the left for outside markers.
fn base_style(kind: &str) -> Style {
    match kind {
        LIST => Style {
            flex_direction: taffy::FlexDirection::Column,
            padding: taffy::Rect {
                left: taffy::LengthPercentage::length(24.0),
                ..taffy::Rect::zero()
            },
            ..Style::default()
        },
        _ => Style::default(),
    }
}

/// An image's content size from its natural size: a known width or height keeps the
/// aspect ratio, like a replaced element with `auto` on the other axis.
fn image_size(natural: (f32, f32), known: (Option<f32>, Option<f32>)) -> (f32, f32) {
    let (iw, ih) = natural;
    let ratio = |a: f32, b: f32| if b > 0.0 { a / b } else { 0.0 };
    match known {
        (Some(w), Some(h)) => (w, h),
        (Some(w), None) => (w, w * ratio(ih, iw)),
        (None, Some(h)) => (h * ratio(iw, ih), h),
        (None, None) => (iw, ih),
    }
}

/// `display: contents` on a box (text elements and fields always keep their box).
fn is_contents(node: &Node) -> bool {
    node.visual.contents && !is_inline_container(&node.kind) && !is_editor_kind(&node.kind)
}

/// `position: fixed` on a node that has a box (the root can't be fixed).
fn is_fixed(id: NodeId, node: &Node) -> bool {
    node.visual.fixed && id != ROOT && !is_contents(node)
}

/// Element types that are inline content when inside a text container.
fn is_inline(kind: &str) -> bool {
    matches!(kind, "span" | TEXT_NODE)
}

/// The UI node tree, owned by Rust and built from React commits (DESIGN.md §3, §5).
pub struct UiTree<L: LayoutEngine = TaffyLayout> {
    /// Boxed: nodes are large (~700 bytes), so the map stays cheap to grow.
    nodes: HashMap<NodeId, Box<Node>>,
    layout: L,
    size: (f32, f32),
    needs_layout: bool,
    /// Absolute rects from the last layout, for drawing and hit testing. Content of a
    /// scroll container is shifted by its scroll offset.
    rects: HashMap<NodeId, Rect>,
    /// Scroll offsets of scrolled elements (x, y), clamped to their range at layout.
    scroll: HashMap<NodeId, (f32, f32)>,
    /// Nodes whose styles use relative units (`em`, `rem`, viewport units), restyled
    /// when what those resolve against changes.
    unit_uses: HashMap<NodeId, Uses>,
    /// Natural sizes of image `src`s, as reported by the app (`None`: failed to load).
    image_sizes: HashMap<String, Option<(f32, f32)>>,
    /// Image `src`s whose size the app hasn't reported yet.
    image_requests: Vec<String>,
    /// `position: fixed` nodes; Taffy lays them out as children of the root.
    fixed: HashSet<NodeId>,
    /// Text fields (`input`, `textarea`) by node.
    editors: HashMap<NodeId, Editor>,
    /// Engine time in ms (caret blinking).
    time_ms: f64,
    /// Text blocks whose content or structure changed since they were last laid out.
    dirty_text: HashSet<NodeId>,
    /// Attribute and state changes since the last restyle, with what changed.
    key_changes: Vec<(NodeId, Vec<Key>)>,
    /// Parents whose children changed since the last restyle (structural selectors).
    structure_changed: HashSet<NodeId>,
    /// Nodes whose computed style must be recomputed from the cascade.
    style_dirty: HashSet<NodeId>,
    sheets: Vec<(u32, Stylesheet)>,
    next_sheet: u32,
    rule_index: RuleIndex,
    deps: Deps,
    /// Inline styles use custom properties or `var()`, so styles go through the
    /// cascade even without stylesheets.
    uses_vars: bool,
    next_generated: u32,
    text: TextEngine,
    /// Parley layouts of text blocks, rebuilt when a block is dirty.
    text_layouts: HashMap<NodeId, parley::Layout<Brush>>,
    /// `…` laid out in the style of text blocks with `text-overflow: ellipsis`.
    ellipses: HashMap<NodeId, parley::Layout<Brush>>,
    /// Nodes whose list marker may need adding, removing or renumbering.
    markers_dirty: HashSet<NodeId>,
    /// How many text blocks have been shaped (for tests and profiling).
    text_builds: u64,
}

impl UiTree<TaffyLayout> {
    /// A tree whose text uses only the bundled font (deterministic; used by tests).
    pub fn new(width: f32, height: f32) -> Self {
        Self::with_layout(TaffyLayout::new(), width, height)
    }

    /// A tree whose text can also fall back to the system's fonts (CJK, emoji, ...).
    pub fn with_system_fonts(width: f32, height: f32) -> Self {
        let mut tree = Self::new(width, height);
        tree.text = TextEngine::new(true);
        tree
    }
}

impl<L: LayoutEngine> UiTree<L> {
    pub fn with_layout(mut layout: L, width: f32, height: f32) -> Self {
        let style = root_style(width, height);
        layout.create_node(ROOT, &style);
        let mut nodes = HashMap::default();
        nodes.insert(
            ROOT,
            Box::new(Node {
                kind: "root".into(),
                parent: None,
                children: Vec::new(),
                style,
                visual: Visual::default(),
                text: None,
                attrs: Attrs::default(),
                state: ElementState::default(),
                inline: Vec::new(),
                generated: None,
                vars: Rc::default(),
            }),
        );
        Self {
            nodes,
            layout,
            size: (width, height),
            needs_layout: true,
            rects: HashMap::default(),
            scroll: HashMap::default(),
            unit_uses: HashMap::default(),
            fixed: HashSet::default(),
            image_sizes: HashMap::default(),
            image_requests: Vec::new(),
            editors: HashMap::default(),
            time_ms: 0.0,
            dirty_text: HashSet::default(),
            key_changes: Vec::new(),
            structure_changed: HashSet::default(),
            style_dirty: HashSet::default(),
            sheets: Vec::new(),
            next_sheet: 1,
            rule_index: RuleIndex::default(),
            deps: Deps::default(),
            uses_vars: false,
            next_generated: FIRST_GENERATED_ID,
            text: TextEngine::new(false),
            text_layouts: HashMap::default(),
            ellipses: HashMap::default(),
            markers_dirty: HashSet::default(),
            text_builds: 0,
        }
    }

    /// Sets the root size in logical pixels (the window's inner size / scale factor).
    pub fn set_size(&mut self, width: f32, height: f32) {
        if self.size == (width, height) {
            return;
        }
        self.size = (width, height);
        let style = root_style(width, height);
        self.layout.set_style(ROOT, &style);
        self.nodes.get_mut(&ROOT).expect("root exists").style = style;
        // Viewport units resolve against the new size.
        let viewport: Vec<NodeId> = self
            .unit_uses
            .iter()
            .filter(|(_, u)| u.viewport)
            .map(|(id, _)| *id)
            .collect();
        self.style_dirty.extend(viewport);
        self.needs_layout = true;
    }

    pub fn size(&self) -> (f32, f32) {
        self.size
    }

    pub fn len(&self) -> usize {
        self.nodes.len() - 1
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    pub fn contains(&self, id: NodeId) -> bool {
        self.nodes.contains_key(&id)
    }

    pub fn kind(&self, id: NodeId) -> Option<&str> {
        self.nodes.get(&id).map(|n| n.kind.as_str())
    }

    pub fn parent(&self, id: NodeId) -> Option<NodeId> {
        self.nodes.get(&id)?.parent
    }

    /// The node's text style after inheritance (CSS computed values).
    pub fn computed_text(&self, id: NodeId) -> ComputedText {
        let mut chain = Vec::new();
        let mut cursor = Some(id);
        while let Some(n) = cursor {
            let Some(node) = self.nodes.get(&n) else {
                break;
            };
            chain.push(&node.visual.text);
            cursor = node.parent;
        }
        chain
            .into_iter()
            .rev()
            .fold(ComputedText::default(), |inherited, props| {
                inherited.child(props)
            })
    }

    /// Adds a stylesheet (CSS text). Returns its id, warnings about parts that were
    /// skipped, and `@font-face` rules for the caller to load (fonts come from the
    /// game folder, which the tree doesn't know about).
    pub fn add_stylesheet(&mut self, css: &str) -> AddedStylesheet {
        self.add_stylesheet_with_base(css, "")
    }

    /// Like [`UiTree::add_stylesheet`], for a stylesheet stored in folder `base` of
    /// the game folder (e.g. `dist` for the bundler's `game.css`): its relative
    /// `url(...)`s are rewritten to be relative to the game folder.
    pub fn add_stylesheet_with_base(&mut self, css: &str, base: &str) -> AddedStylesheet {
        let mut sheet = parse_stylesheet(css);
        if !base.is_empty() {
            for rule in &mut sheet.rules {
                for decl in &mut rule.declarations {
                    decl.value = crate::css::rebase_urls(&decl.value, base);
                }
            }
            for face in &mut sheet.font_faces {
                if !face.src.contains(':') {
                    let src = face.src.strip_prefix("./").unwrap_or(&face.src);
                    face.src = format!("{}/{src}", base.trim_end_matches(['/', '\\']));
                }
            }
        }
        // Drop declarations that won't apply, with a warning, so they aren't
        // re-reported on every restyle.
        let mut warnings = std::mem::take(&mut sheet.warnings);
        for rule in &mut sheet.rules {
            rule.declarations.retain(|d| {
                // Variables are only known per element, so var() values are
                // checked when they're used.
                if d.prop.starts_with("--")
                    || d.prop == "content"
                    || d.value.contains("var(")
                    || WideKeyword::parse(&Value::from(d.value.as_str())).is_some()
                {
                    return true;
                }
                // Relative units resolve per element; check the value with typical
                // ones (invalid math is rejected either way).
                let value = if crate::units::needs_resolution(&d.value) {
                    let ctx = UnitContext {
                        em: 16.0,
                        rem: 16.0,
                        viewport: (1000.0, 1000.0),
                    };
                    match crate::units::resolve(&d.value, &ctx) {
                        Some((resolved, _)) => resolved,
                        None => {
                            warnings.push(format!("invalid math in `{}: {}`", d.prop, d.value));
                            return false;
                        }
                    }
                } else {
                    d.value.clone()
                };
                let mut style = Style::default();
                let mut visual = Visual::default();
                match apply_style(
                    &mut style,
                    &mut visual,
                    &d.prop,
                    &crate::cascade::css_value(&value),
                ) {
                    Ok(()) => true,
                    Err(e) => {
                        warnings.push(e.to_string());
                        false
                    }
                }
            });
        }
        let id = self.next_sheet;
        self.next_sheet += 1;
        let font_faces = sheet.font_faces.clone();
        self.sheets.push((id, sheet));
        self.restyle_everything();
        AddedStylesheet {
            id,
            warnings,
            font_faces,
        }
    }

    /// Removes a stylesheet added with [`UiTree::add_stylesheet`].
    pub fn remove_stylesheet(&mut self, id: u32) -> bool {
        let before = self.sheets.len();
        self.sheets.retain(|(sheet_id, _)| *sheet_id != id);
        let removed = self.sheets.len() != before;
        if removed {
            self.restyle_everything();
        }
        removed
    }

    fn restyle_everything(&mut self) {
        let sheets: Vec<&Stylesheet> = self.sheets.iter().map(|(_, s)| s).collect();
        self.rule_index = RuleIndex::build(&sheets);
        let mut deps = Deps::default();
        for sheet in &sheets {
            deps.add_sheet(sheet);
        }
        self.deps = deps;
        let all: Vec<NodeId> = self.nodes.keys().copied().collect();
        self.style_dirty.extend(all);
        self.needs_layout = true;
    }

    /// Paint properties after the cascade (for tests and tools).
    pub fn visual(&self, id: NodeId) -> Option<&Visual> {
        self.nodes.get(&id).map(|n| &n.visual)
    }

    /// Whether `id` is `::before`/`::after` content generated by a stylesheet.
    pub fn is_generated(&self, id: NodeId) -> bool {
        self.nodes.get(&id).is_some_and(|n| n.generated.is_some())
    }

    /// Creates, updates or removes the `pseudo` content of element `id`.
    /// Whether `id` is a list item: an element child of a `list`, or `display: list-item`.
    fn is_list_item(&self, id: NodeId) -> bool {
        let Some(node) = self.nodes.get(&id) else {
            return false;
        };
        if node.kind == TEXT_NODE || node.generated.is_some() || node.style.display == Display::None
        {
            return false;
        }
        node.visual.list_item
            || node
                .parent
                .and_then(|p| self.nodes.get(&p))
                .is_some_and(|p| p.kind == LIST)
    }

    /// Adds, updates or removes the markers of the queued nodes.
    fn refresh_markers(&mut self) {
        if self.markers_dirty.is_empty() {
            return;
        }
        let ids: Vec<NodeId> = self.markers_dirty.drain().collect();
        let mut caches = selectors::context::SelectorCaches::default();
        for id in ids {
            self.update_marker(id, &mut caches);
        }
    }

    /// Keeps `id`'s generated `::marker` child in step with its list styles and its
    /// place among its siblings.
    fn update_marker(&mut self, id: NodeId, caches: &mut selectors::context::SelectorCaches) {
        if !self.nodes.contains_key(&id) {
            return;
        }
        let existing = self.children(id).iter().copied().find(|c| {
            self.nodes.get(c).and_then(|n| n.generated) == Some(PseudoElement::Marker)
                && self.kind(*c) != Some(TEXT_NODE)
        });
        let text = self.computed_text(id);
        enum Marker {
            Text(String),
            Image(String),
        }
        let wanted = if self.is_list_item(id) {
            match &text.list_image {
                Some(url) => Some(Marker::Image(url.clone())),
                None => {
                    let parent = self.parent(id).unwrap_or(ROOT);
                    let n = self
                        .children(parent)
                        .iter()
                        .filter(|c| self.is_list_item(**c))
                        .position(|c| *c == id)
                        .map_or(1, |i| i + 1);
                    text.list_style_type.marker(n).map(Marker::Text)
                }
            }
        } else {
            None
        };
        // The marker's kind must match: text markers are spans, image markers images.
        let existing_kind = existing.and_then(|e| self.kind(e)).map(str::to_owned);
        let fits = matches!(
            (&wanted, existing_kind.as_deref()),
            (Some(Marker::Text(_)), Some("span")) | (Some(Marker::Image(_)), Some(IMAGE))
        );
        if let Some(old) = existing.filter(|_| !fits) {
            let mut changed = HashSet::default();
            self.detach(old, &mut changed);
            self.destroy_subtree(old);
            self.sync_children(id);
            self.needs_layout = true;
        }
        let Some(wanted) = wanted else {
            return;
        };
        let marker = match existing.filter(|_| fits) {
            Some(m) => m,
            None => match &wanted {
                Marker::Text(_) => self.insert_generated(id, PseudoElement::Marker),
                Marker::Image(_) => self.insert_marker_image(id),
            },
        };
        // Outside markers hang left of the item; a text item's marker can only be
        // inline, so it reads as `inside` there.
        let item_is_text = self
            .nodes
            .get(&id)
            .is_some_and(|n| is_inline_container(&n.kind));
        let outside = !text.list_inside && !item_is_text;
        let gap = (text.font_size * 0.5).round();
        let mut style = Style::default();
        let mut visual = Visual::default();
        if outside {
            style.position = taffy::Position::Absolute;
            style.inset.right = taffy::LengthPercentageAuto::percent(1.0);
            style.inset.top = taffy::LengthPercentageAuto::length(0.0);
            style.padding.right = taffy::LengthPercentage::length(gap);
        } else if !item_is_text {
            style.margin.right = taffy::LengthPercentageAuto::length(gap);
            style.flex_shrink = 0.0;
        }
        visual.text.white_space = Some(crate::text_style::WhiteSpace::Pre);
        if !self.sheets.is_empty() {
            let owner = self.nodes.get(&id).map(|n| (&n.style, &n.visual));
            for (prop, value) in self.pseudo_declarations(id, PseudoElement::Marker, caches) {
                if prop.starts_with("--") || prop == "content" {
                    continue;
                }
                match WideKeyword::parse(&value) {
                    Some(keyword) => {
                        let _ = apply_wide_keyword(&mut style, &mut visual, &prop, keyword, owner);
                    }
                    None => {
                        let _ = apply_style(&mut style, &mut visual, &prop, &value);
                    }
                }
            }
        }
        let content = match wanted {
            Marker::Text(t) if item_is_text || text.list_inside => {
                // Inline: a no-break space keeps the gap from collapsing.
                format!("{t}\u{00A0}")
            }
            Marker::Text(t) => t,
            Marker::Image(url) => {
                if let Some(node) = self.nodes.get_mut(&marker)
                    && node.attrs.src.as_deref() != Some(url.as_str())
                {
                    node.attrs.src = Some(url.clone());
                    self.request_image(&url);
                    self.layout.mark_dirty(marker);
                }
                String::new()
            }
        };
        let text_child = self.children(marker).first().copied();
        if let Some(node) = self.nodes.get_mut(&marker) {
            let restyled = node.style != style || node.visual != visual;
            node.style = style.clone();
            node.visual = visual;
            if restyled {
                self.layout.set_style(marker, &style);
                if let Some(root) = self.text_root_of(marker) {
                    self.dirty_text.insert(root);
                }
            }
        }
        if let Some(t) = text_child
            && let Some(node) = self.nodes.get_mut(&t)
            && node.text.as_deref() != Some(content.as_str())
        {
            node.text = Some(content);
            if let Some(root) = self.text_root_of(t) {
                self.dirty_text.insert(root);
            }
        }
        self.needs_layout = true;
    }

    /// Adds an `image` marker as `id`'s first child.
    fn insert_marker_image(&mut self, parent: NodeId) -> NodeId {
        let id = NodeId(self.next_generated);
        self.next_generated += 1;
        let style = Style::default();
        self.layout.create_node(id, &style);
        self.layout.set_measured(id, true);
        self.nodes.insert(
            id,
            Box::new(Node {
                kind: IMAGE.to_owned(),
                parent: Some(parent),
                children: Vec::new(),
                style,
                visual: Visual::default(),
                text: None,
                attrs: Attrs::default(),
                state: ElementState::default(),
                inline: Vec::new(),
                generated: Some(PseudoElement::Marker),
                vars: Rc::default(),
            }),
        );
        self.nodes
            .get_mut(&parent)
            .expect("parent exists")
            .children
            .insert(0, id);
        self.sync_children(parent);
        id
    }

    /// `pseudo`'s matched declarations for `id`, in cascade order, with `var()` and
    /// relative units resolved.
    fn pseudo_declarations(
        &self,
        id: NodeId,
        pseudo: PseudoElement,
        caches: &mut selectors::context::SelectorCaches,
    ) -> Vec<(String, Value)> {
        let sheets: Vec<&Stylesheet> = self.sheets.iter().map(|(_, s)| s).collect();
        let (normal, important) = matched_declarations(
            self,
            &sheets,
            &self.rule_index,
            id,
            Target::Pseudo(pseudo),
            caches,
        );
        let vars = self
            .nodes
            .get(&id)
            .map(|n| n.vars.clone())
            .unwrap_or_default();
        let lookup = |name: &str| vars.get(name).cloned();
        let units = UnitContext {
            em: self.computed_text(id).font_size,
            rem: self.computed_text(ROOT).font_size,
            viewport: self.size,
        };
        let resolve = |value: &Value| -> Option<Value> {
            let Value::String(text) = value else {
                return Some(value.clone());
            };
            let mut text = text.clone();
            if text.contains("var(") {
                text = substitute_vars(&text, &lookup)?;
            }
            if crate::units::needs_resolution(&text) {
                text = crate::units::resolve(&text, &units)?.0;
            }
            Some(crate::cascade::css_value(&text))
        };
        normal
            .iter()
            .chain(important.iter())
            .filter_map(|m| Some((m.prop.clone(), resolve(&m.value)?)))
            .collect()
    }

    fn update_pseudo(
        &mut self,
        id: NodeId,
        pseudo: PseudoElement,
        caches: &mut selectors::context::SelectorCaches,
    ) {
        let existing = self.children(id).iter().copied().find(|c| {
            self.nodes.get(c).and_then(|n| n.generated) == Some(pseudo)
                && self.kind(*c) != Some(TEXT_NODE)
        });
        let ordered = self.pseudo_declarations(id, pseudo, caches);
        let content =
            ordered
                .iter()
                .rev()
                .find(|(p, _)| p == "content")
                .and_then(|(_, v)| match v {
                    Value::String(s) => parse_content(s, self.attrs(id)),
                    Value::Number(n) => Some(n.to_string()),
                    _ => None,
                });

        let Some(content) = content else {
            if let Some(old) = existing {
                let mut changed = HashSet::default();
                self.detach(old, &mut changed);
                self.destroy_subtree(old);
                self.sync_children(id);
                self.needs_layout = true;
            }
            return;
        };

        let span = match existing {
            Some(span) => span,
            None => self.insert_generated(id, pseudo),
        };
        let mut style = Style::default();
        let mut visual = Visual::default();
        let owner = self.nodes.get(&id).map(|n| (&n.style, &n.visual));
        for (prop, value) in &ordered {
            if prop.starts_with("--") || prop == "content" {
                continue;
            }
            match WideKeyword::parse(value) {
                Some(keyword) => {
                    let _ = apply_wide_keyword(&mut style, &mut visual, prop, keyword, owner);
                }
                None => {
                    let _ = apply_style(&mut style, &mut visual, prop, value);
                }
            }
        }
        let text_child = self.children(span).first().copied();
        if let Some(node) = self.nodes.get_mut(&span) {
            let restyled = node.style != style || node.visual != visual;
            node.style = style.clone();
            node.visual = visual;
            if restyled {
                self.layout.set_style(span, &style);
                if let Some(root) = self.text_root_of(span) {
                    self.dirty_text.insert(root);
                }
            }
        }
        if let Some(t) = text_child
            && let Some(node) = self.nodes.get_mut(&t)
            && node.text.as_deref() != Some(content.as_str())
        {
            node.text = Some(content);
            if let Some(root) = self.text_root_of(t) {
                self.dirty_text.insert(root);
            }
        }
        self.needs_layout = true;
    }

    /// Adds an empty generated span (with a text child) as the first or last child.
    fn insert_generated(&mut self, parent: NodeId, pseudo: PseudoElement) -> NodeId {
        let span = NodeId(self.next_generated);
        let text = NodeId(self.next_generated + 1);
        self.next_generated += 2;
        for (id, kind, text_value, children, parent_id) in [
            (span, "span", None, vec![text], parent),
            (text, TEXT_NODE, Some(String::new()), Vec::new(), span),
        ] {
            let style = Style::default();
            self.layout.create_node(id, &style);
            self.nodes.insert(
                id,
                Box::new(Node {
                    kind: kind.to_owned(),
                    parent: Some(parent_id),
                    children,
                    style,
                    visual: Visual::default(),
                    text: text_value,
                    attrs: Attrs::default(),
                    state: ElementState::default(),
                    inline: Vec::new(),
                    generated: Some(pseudo),
                    vars: Rc::default(),
                }),
            );
        }
        let first_is_marker = self
            .children(parent)
            .first()
            .and_then(|c| self.nodes.get(c))
            .is_some_and(|n| n.generated == Some(PseudoElement::Marker));
        let siblings = &mut self.nodes.get_mut(&parent).expect("parent exists").children;
        match pseudo {
            // The marker comes first, then ::before.
            PseudoElement::Marker => siblings.insert(0, span),
            PseudoElement::Before => siblings.insert(usize::from(first_is_marker), span),
            PseudoElement::After => siblings.push(span),
        }
        self.layout.set_children(span, &[]);
        self.sync_children(parent);
        let is_root = self.is_text_root(span);
        self.layout.set_measured(span, is_root);
        if let Some(root) = self.text_root_of(span) {
            self.dirty_text.insert(root);
        }
        span
    }

    /// Re-sends `id`'s children to the layout engine (inline content excluded).
    fn sync_children(&mut self, id: NodeId) {
        self.set_layout_children(id);
        if let Some(root) = self.text_root_of(id) {
            self.dirty_text.insert(root);
        }
    }

    /// Marks what changing `keys` on `id` can affect, using the stylesheets'
    /// dependencies: the node itself; its subtree if the keys appear in ancestor
    /// positions; its later siblings if they appear before `+`/`~`; its ancestors
    /// for `:has()` and `:focus-within`.
    fn invalidate_keys(&mut self, id: NodeId, keys: &[Key]) {
        self.style_dirty.insert(id);
        let hits = |set: &HashSet<Key>| keys.iter().any(|k| set.contains(k));
        if hits(&self.deps.ancestor) {
            self.mark_subtree(id);
        }
        if hits(&self.deps.sibling) {
            self.mark_later_siblings(id);
        }
        let focus = keys.contains(&Key::Focus) && self.deps.focus_within;
        if hits(&self.deps.has) || focus {
            self.mark_ancestors(id);
        }
    }

    /// A parent's children changed: positions (`:nth-child`, `+`) and `:empty`/`:has`
    /// may change. New nodes are already marked when created.
    fn invalidate_structure(&mut self, parent: NodeId) {
        if !self.deps.structural {
            return;
        }
        self.style_dirty.insert(parent);
        for child in self.children(parent).to_vec() {
            self.mark_subtree(child);
        }
        if self.deps.uses_has {
            self.mark_ancestors(parent);
        }
    }

    fn mark_subtree(&mut self, id: NodeId) {
        let mut stack = vec![id];
        while let Some(n) = stack.pop() {
            self.style_dirty.insert(n);
            stack.extend_from_slice(self.children(n));
        }
    }

    fn mark_later_siblings(&mut self, id: NodeId) {
        if let Some(parent) = self.parent(id) {
            let siblings = self.children(parent).to_vec();
            if let Some(i) = siblings.iter().position(|c| *c == id) {
                for s in &siblings[i + 1..] {
                    self.mark_subtree(*s);
                }
            }
        }
    }

    fn mark_ancestors(&mut self, id: NodeId) {
        let mut cursor = self.parent(id);
        while let Some(a) = cursor {
            self.style_dirty.insert(a);
            cursor = self.parent(a);
        }
    }

    /// Recomputes the style of every dirty node from the cascade, in tree order.
    fn restyle_dirty(&mut self) {
        let key_changes = std::mem::take(&mut self.key_changes);
        let structure_changed: Vec<NodeId> = self.structure_changed.drain().collect();
        if self.sheets.is_empty() && !self.uses_vars {
            // Without stylesheets inline styles are applied directly as they arrive.
            self.style_dirty.clear();
            return;
        }
        for (id, keys) in key_changes {
            if self.nodes.contains_key(&id) {
                self.invalidate_keys(id, &keys);
            }
        }
        for id in structure_changed {
            if self.nodes.contains_key(&id) {
                self.invalidate_structure(id);
            }
        }
        if self.style_dirty.is_empty() {
            return;
        }
        let mut caches = selectors::context::SelectorCaches::default();
        let mut stack = vec![ROOT];
        while let Some(id) = stack.pop() {
            if self.style_dirty.remove(&id) {
                self.restyle(id, &mut caches);
            }
            if self.style_dirty.is_empty() {
                break;
            }
            stack.extend(self.children(id).iter().rev());
        }
        self.style_dirty.clear();
    }

    fn restyle(&mut self, id: NodeId, caches: &mut selectors::context::SelectorCaches) {
        let Some(node) = self.nodes.get(&id) else {
            return;
        };
        if node.kind == TEXT_NODE || node.generated.is_some() {
            return;
        }
        let sheets: Vec<&Stylesheet> = self.sheets.iter().map(|(_, s)| s).collect();
        let (normal, important) =
            matched_declarations(self, &sheets, &self.rule_index, id, Target::Element, caches);

        let mut style = if id == ROOT {
            root_style(self.size.0, self.size.1)
        } else {
            base_style(&node.kind)
        };
        let mut visual = Visual::default();
        let parent_text = match node.parent {
            Some(p) => self.computed_text(p),
            None => ComputedText::default(),
        };
        let rem = if id == ROOT {
            ComputedText::default().font_size
        } else {
            self.computed_text(ROOT).font_size
        };
        let mut units = UnitContext {
            em: parent_text.font_size,
            rem,
            viewport: self.size,
        };
        let mut unit_uses = Uses::default();

        // Every declaration in cascade order: rules, inline styles, !important rules.
        let ordered: Vec<(&str, Value)> = normal
            .iter()
            .map(|m| (m.prop.as_str(), m.value.clone()))
            .chain(node.inline.iter().map(|(p, v)| (p.as_str(), v.clone())))
            .chain(important.iter().map(|m| (m.prop.as_str(), m.value.clone())))
            .collect();

        // Custom properties inherit; this node's declarations override them.
        let inherited = node
            .parent
            .and_then(|p| self.nodes.get(&p))
            .map(|p| p.vars.clone())
            .unwrap_or_default();
        let mut vars = inherited;
        for (prop, value) in &ordered {
            if prop.starts_with("--") {
                let text = match value {
                    Value::String(s) => s.clone(),
                    Value::Number(n) => n.to_string(),
                    Value::Bool(b) => b.to_string(),
                    _ => continue,
                };
                if vars.get(*prop) != Some(&text) {
                    Rc::make_mut(&mut vars).insert((*prop).to_owned(), text);
                }
            }
        }

        // Resolves `var()`, then relative units and math. `None`: invalid at computed
        // time, so the declaration is ignored.
        let compute =
            |prop: &str, value: &Value, units: &UnitContext, uses: &mut Uses| -> Option<Value> {
                let Value::String(text) = value else {
                    return Some(value.clone());
                };
                let mut text = std::borrow::Cow::Borrowed(text.as_str());
                if text.contains("var(") {
                    let lookup = |name: &str| vars.get(name).cloned();
                    text = std::borrow::Cow::Owned(substitute_vars(&text, &lookup)?);
                }
                if crate::units::needs_resolution_for(prop, &text) {
                    let (resolved, u) = crate::units::resolve(&text, units)?;
                    *uses = uses.union(u);
                    text = std::borrow::Cow::Owned(resolved);
                }
                Some(match text {
                    std::borrow::Cow::Borrowed(_) => value.clone(),
                    std::borrow::Cow::Owned(t) => crate::cascade::css_value(&t),
                })
            };
        // `em` means the element's own font size, so resolve `fontSize` first (its own
        // `em` is the parent's size).
        let mut sized = Visual::default();
        for (prop, value) in ordered.iter().filter(|(p, _)| *p == "fontSize") {
            if let Some(v) = compute(prop, value, &units, &mut unit_uses) {
                let _ = apply_style(&mut Style::default(), &mut sized, prop, &v);
            }
        }
        units.em = parent_text.child(&sized.text).font_size;
        for (prop, value) in &ordered {
            if prop.starts_with("--") || *prop == "content" {
                continue;
            }
            let ctx = if *prop == "fontSize" {
                UnitContext {
                    em: parent_text.font_size,
                    ..units
                }
            } else {
                units
            };
            if let Some(keyword) = WideKeyword::parse(value) {
                let parent = node.parent.and_then(|p| self.nodes.get(&p));
                let parent = parent.map(|p| (&p.style, &p.visual));
                let _ = apply_wide_keyword(&mut style, &mut visual, prop, keyword, parent);
                continue;
            }
            let Some(value) = compute(prop, value, &ctx, &mut unit_uses) else {
                continue;
            };
            let _ = apply_style(&mut style, &mut visual, prop, &value);
        }
        if unit_uses.any() {
            self.unit_uses.insert(id, unit_uses);
        } else {
            self.unit_uses.remove(&id);
        }
        // `dir` acts like the UA rule `[dir=rtl] { direction: rtl }`: any author CSS wins.
        if visual.text.direction.is_none() {
            visual.text.direction = node.attrs.dir;
        }
        if id == ROOT {
            // The root is always the size of the window.
            style.size = root_style(self.size.0, self.size.1).size;
        }

        let vars_changed = node.vars != vars;
        let order_changed = node.visual.order != visual.order;
        let boxes_changed =
            node.visual.contents != visual.contents || node.visual.fixed != visual.fixed;
        let parent = node.parent;
        let node = self.nodes.get_mut(&id).expect("checked above");
        node.vars = vars;
        let text_changed = node.visual.text != visual.text;
        let style_changed = node.style != style;
        node.style = style;
        node.visual = visual;
        if style_changed {
            let style = node.style.clone();
            self.layout.set_style(id, &style);
        }
        if boxes_changed {
            self.update_fixed(id);
            self.set_layout_children(id);
            self.set_layout_children(ROOT);
        }
        if (order_changed || boxes_changed)
            && let Some(p) = parent
        {
            self.sync_children(p);
        }
        if id != ROOT && !self.sheets.is_empty() {
            for pseudo in [PseudoElement::Before, PseudoElement::After] {
                self.update_pseudo(id, pseudo, caches);
            }
        }
        // Its marker (if it's a list item) and its children's (if it's a list).
        self.markers_dirty.insert(id);
        let children = self.children(id).to_vec();
        self.markers_dirty.extend(children);
        if vars_changed {
            // Children inherit the variables: restyle them too (they come later in
            // tree order, so this pass picks them up).
            let children = self.children(id).to_vec();
            for c in children {
                let mut stack = vec![c];
                while let Some(n) = stack.pop() {
                    self.style_dirty.insert(n);
                    stack.extend_from_slice(self.children(n));
                }
            }
        }
        if text_changed {
            let mut stack = vec![id];
            while let Some(n) = stack.pop() {
                if self.is_text_root(n) {
                    self.dirty_text.insert(n);
                }
                // A font size change moves `em` (and, from the root, `rem`) values below.
                if n != id
                    && self
                        .unit_uses
                        .get(&n)
                        .is_some_and(|u| u.em || (id == ROOT && u.rem))
                {
                    self.style_dirty.insert(n);
                }
                stack.extend_from_slice(self.children(n));
            }
            if let Some(root) = self.text_root_of(id) {
                self.dirty_text.insert(root);
            }
        }
        self.needs_layout = true;
    }

    /// The node's attributes (`className`, `id`, `data-*`, ...).
    pub fn attrs(&self, id: NodeId) -> Option<&Attrs> {
        self.nodes.get(&id).map(|n| &n.attrs)
    }

    /// The node's interaction state (`:hover`, `:active`, `:focus`).
    pub fn state(&self, id: NodeId) -> ElementState {
        self.nodes.get(&id).map(|n| n.state).unwrap_or_default()
    }

    /// Sets interaction state (driven by input handling; tests set it directly).
    pub fn set_state(&mut self, id: NodeId, state: ElementState) {
        if let Some(node) = self.nodes.get_mut(&id)
            && node.state != state
        {
            let old = node.state;
            node.state = state;
            let mut keys = Vec::new();
            for (changed, key) in [
                (old.hover != state.hover, Key::Hover),
                (old.active != state.active, Key::Active),
                (old.focus != state.focus, Key::Focus),
                (old.focus_visible != state.focus_visible, Key::FocusVisible),
            ] {
                if changed {
                    keys.push(key);
                }
            }
            self.key_changes.push((id, keys));
            self.needs_layout = true;
        }
    }

    /// The characters of a `#text` node.
    pub fn text(&self, id: NodeId) -> Option<&str> {
        self.nodes.get(&id)?.text.as_deref()
    }

    /// Whether `id` is laid out as a block of text: a `text` element, or a span or
    /// text node outside any text container (an anonymous text block).
    pub fn is_text_root(&self, id: NodeId) -> bool {
        let Some(node) = self.nodes.get(&id) else {
            return false;
        };
        if node.kind == "text" {
            return true;
        }
        is_inline(&node.kind) && !self.inside_inline_container(id)
    }

    fn inside_inline_container(&self, id: NodeId) -> bool {
        self.parent(id)
            .and_then(|p| self.nodes.get(&p))
            .is_some_and(|p| is_inline_container(&p.kind))
    }

    /// The text block that lays out `id`, if `id` is text content or a text block.
    pub fn text_root_of(&self, id: NodeId) -> Option<NodeId> {
        let mut cursor = id;
        loop {
            if self.is_text_root(cursor) {
                return Some(cursor);
            }
            let node = self.nodes.get(&cursor)?;
            if !is_inline(&node.kind) && !is_inline_container(&node.kind) {
                return None;
            }
            cursor = node.parent?;
        }
    }

    /// The plain text of a text block: all `#text` descendants in order.
    pub fn text_content(&self, id: NodeId) -> String {
        let mut out = String::new();
        let mut stack = vec![id];
        while let Some(n) = stack.pop() {
            let Some(node) = self.nodes.get(&n) else {
                continue;
            };
            if let Some(t) = &node.text {
                out.push_str(t);
            }
            stack.extend(node.children.iter().rev());
        }
        out
    }

    /// Registers font data for this tree's text (see [`TextEngine::register_font`])
    /// and re-lays out all text, since fallback choices may change.
    pub fn register_font(
        &mut self,
        data: Vec<u8>,
        family: Option<&str>,
        weight: Option<f32>,
        italic: Option<bool>,
    ) -> Result<Vec<String>, String> {
        let names = self.text.register_font(data, family, weight, italic)?;
        let roots: Vec<NodeId> = self
            .nodes
            .keys()
            .copied()
            .filter(|id| self.is_text_root(*id))
            .collect();
        self.dirty_text.extend(roots);
        self.needs_layout = true;
        Ok(names)
    }

    /// The Parley layout of a text block, as of the last layout pass.
    pub fn text_layout(&self, id: NodeId) -> Option<&parley::Layout<Brush>> {
        self.text_layouts.get(&id)
    }

    fn build_text_layout(&mut self, root: NodeId) -> parley::Layout<Brush> {
        let block = self.computed_text(root);
        if block.text_overflow == TextOverflow::Ellipsis {
            let mut dots = self
                .text
                .build(&block, &[("\u{2026}".to_owned(), block.clone())]);
            dots.break_all_lines(None);
            self.ellipses.insert(root, dots);
        } else {
            self.ellipses.remove(&root);
        }
        let mut runs = Vec::new();
        let mut word_start = true;
        // Walk the inline content in order, carrying each node's computed style.
        let mut stack = vec![(root, block.clone())];
        while let Some((id, style)) = stack.pop() {
            let Some(node) = self.nodes.get(&id) else {
                continue;
            };
            let style = if id == root {
                style
            } else {
                style.child(&node.visual.text)
            };
            if let Some(t) = &node.text {
                let text = style.text_transform.apply(t, &mut word_start);
                runs.push((text, style.clone()));
            }
            for child in node.children.iter().rev() {
                stack.push((*child, style.clone()));
            }
        }
        self.text_builds += 1;
        self.text.build(&block, &runs)
    }

    /// How many text blocks have been shaped since the tree was created.
    pub fn text_build_count(&self) -> u64 {
        self.text_builds
    }

    /// Text blocks changed since the last call (clears the set).
    pub fn take_dirty_text(&mut self) -> Vec<NodeId> {
        let dirty: Vec<NodeId> = self.dirty_text.drain().collect();
        dirty
            .into_iter()
            .filter(|id| self.nodes.contains_key(id))
            .collect()
    }

    pub fn children(&self, id: NodeId) -> &[NodeId] {
        self.nodes.get(&id).map_or(&[], |n| &n.children)
    }

    /// Applies one commit. Bad ops are skipped and returned; the rest still apply.
    pub fn apply_commit(&mut self, commit: &Commit) -> Vec<UiError> {
        let mut errors = Vec::new();
        let mut children_changed = HashSet::default();
        let mut styles_changed = HashSet::default();
        let mut text_changed = HashSet::default();
        let mut text_style_changed = HashSet::default();

        for op in &commit.ops {
            if let Err(e) = self.apply_op(
                op,
                &mut children_changed,
                &mut styles_changed,
                &mut text_changed,
                &mut text_style_changed,
            ) {
                errors.push(e);
            }
        }

        // Sync with the layout engine once per commit, not once per op.
        for id in styles_changed {
            if let Some(node) = self.nodes.get(&id) {
                self.layout.set_style(id, &node.style);
            }
        }
        self.structure_changed
            .extend(children_changed.iter().copied());
        for id in &children_changed {
            self.update_fixed(*id);
            // Items added, removed or moved renumber their siblings' markers.
            let children = self.children(*id).to_vec();
            self.markers_dirty.extend(children);
        }
        if !self.fixed.is_empty() {
            // Newly attached subtrees may hold fixed nodes, which the root lays out.
            children_changed.insert(ROOT);
        }
        for id in &children_changed {
            self.set_layout_children(*id);
        }
        // Text blocks whose content changed. A changed parent may also have new
        // text children, which are text blocks of their own.
        let touched = children_changed
            .iter()
            .flat_map(|id| {
                let kids = self.children(*id).to_vec();
                std::iter::once(*id).chain(kids)
            })
            .chain(text_changed.iter().copied())
            .collect::<Vec<_>>();
        for id in touched {
            // Text blocks, text fields and images are measured leaves.
            let is_root = self.is_text_root(id)
                || self.editors.contains_key(&id)
                || self.nodes.get(&id).is_some_and(|n| n.kind == IMAGE);
            self.layout.set_measured(id, is_root);
            if !is_root {
                self.text_layouts.remove(&id);
                self.ellipses.remove(&id);
            }
            if let Some(root) = self.text_root_of(id) {
                self.dirty_text.insert(root);
            }
        }
        // Text properties inherit, so every text block at or below the node changes,
        // and so do `em` values below it (`rem` too, from the root).
        for id in text_style_changed {
            if let Some(root) = self.text_root_of(id) {
                self.dirty_text.insert(root);
            }
            let mut stack = vec![id];
            while let Some(n) = stack.pop() {
                if self.is_text_root(n) {
                    self.dirty_text.insert(n);
                }
                if self
                    .unit_uses
                    .get(&n)
                    .is_some_and(|u| u.em || (id == ROOT && u.rem))
                {
                    self.style_dirty.insert(n);
                }
                stack.extend_from_slice(self.children(n));
            }
        }
        if !commit.ops.is_empty() {
            self.needs_layout = true;
        }
        errors
    }

    fn apply_op(
        &mut self,
        op: &Value,
        children_changed: &mut HashSet<NodeId>,
        styles_changed: &mut HashSet<NodeId>,
        text_changed: &mut HashSet<NodeId>,
        text_style_changed: &mut HashSet<NodeId>,
    ) -> Result<(), UiError> {
        let Value::Array(args) = op else {
            return Err(UiError(format!("op must be an array, got {op:?}")));
        };
        let opcode = args
            .first()
            .and_then(Value::as_f64)
            .ok_or_else(|| UiError(format!("op is missing its opcode: {op:?}")))?;
        let arg = |i: usize| {
            args.get(i)
                .ok_or_else(|| UiError(format!("op is missing argument {i}: {op:?}")))
        };
        let id = |i: usize| node_id(arg(i)?);

        match opcode as u32 {
            opcodes::CREATE => {
                let id = id(1)?;
                if id == ROOT || self.nodes.contains_key(&id) {
                    return Err(UiError(format!("node {id} already exists")));
                }
                let kind = arg(2)?
                    .as_str()
                    .ok_or_else(|| UiError(format!("CREATE needs an element type: {op:?}")))?;
                let style = base_style(kind);
                self.layout.create_node(id, &style);
                self.style_dirty.insert(id);
                if is_editor_kind(kind) {
                    self.editors.insert(id, Editor::new(kind == "textarea"));
                    // Sized by `measure` from the font, like a replaced element.
                    self.layout.set_measured(id, true);
                }
                if kind == IMAGE {
                    // Sized by `measure` from the image's natural size.
                    self.layout.set_measured(id, true);
                }
                self.nodes.insert(
                    id,
                    Box::new(Node {
                        kind: kind.to_owned(),
                        parent: None,
                        children: Vec::new(),
                        style,
                        visual: Visual::default(),
                        text: None,
                        attrs: Attrs::default(),
                        state: ElementState::default(),
                        inline: Vec::new(),
                        generated: None,
                        vars: Rc::default(),
                    }),
                );
            }
            opcodes::CREATE_TEXT => {
                let id = id(1)?;
                if id == ROOT || self.nodes.contains_key(&id) {
                    return Err(UiError(format!("node {id} already exists")));
                }
                let text = arg(2)?
                    .as_str()
                    .ok_or_else(|| UiError(format!("CREATE_TEXT needs a string: {op:?}")))?;
                let style = Style::default();
                self.layout.create_node(id, &style);
                self.nodes.insert(
                    id,
                    Box::new(Node {
                        kind: TEXT_NODE.to_owned(),
                        parent: None,
                        children: Vec::new(),
                        style,
                        visual: Visual::default(),
                        text: Some(text.to_owned()),
                        attrs: Attrs::default(),
                        state: ElementState::default(),
                        inline: Vec::new(),
                        generated: None,
                        vars: Rc::default(),
                    }),
                );
            }
            opcodes::SET_ATTRS => {
                let id = id(1)?;
                let node = self.node_mut(id)?;
                let before = node.attrs.clone();
                let pairs = &args[2..];
                if pairs.len() % 2 != 0 {
                    return Err(UiError(format!("SET_ATTRS needs name/value pairs: {op:?}")));
                }
                let mut problems = Vec::new();
                for pair in pairs.chunks(2) {
                    let Some(name) = pair[0].as_str() else {
                        problems.push(format!("attribute name must be a string: {:?}", pair[0]));
                        continue;
                    };
                    if let Err(e) = node.attrs.set(name, &pair[1]) {
                        problems.push(e);
                    }
                }
                let keys = attr_keys_changed(&before, &node.attrs);
                let attrs = node.attrs.clone();
                if node.kind == IMAGE && before.src != attrs.src {
                    if let Some(src) = &attrs.src {
                        self.request_image(src);
                    }
                    self.layout.mark_dirty(id);
                }
                if before.dir != attrs.dir {
                    if self.sheets.is_empty() && !self.uses_vars {
                        dir_fallback(self.node_mut(id)?);
                    } else {
                        self.style_dirty.insert(id);
                    }
                    text_style_changed.insert(id);
                }
                if !keys.is_empty() {
                    self.key_changes.push((id, keys));
                }
                if let Some(editor) = self.editors.get_mut(&id) {
                    // A controlled `value` wins; `defaultValue` only fills a new field.
                    let value = match (&attrs.value, &before.value) {
                        (Some(v), _) => Some(v.as_str()),
                        (None, None) if before.default_value.is_none() => {
                            attrs.default_value.as_deref()
                        }
                        _ => None,
                    };
                    if let Some(v) = value {
                        editor.set_value(v);
                    }
                    editor.set_placeholder(attrs.placeholder.as_deref());
                    editor.rows = attrs.rows.unwrap_or(TEXTAREA_ROWS);
                    self.layout.mark_dirty(id);
                    self.needs_layout = true;
                }
                if !problems.is_empty() {
                    return Err(UiError(format!("node {id}: {}", problems.join("; "))));
                }
            }
            opcodes::SET_TEXT => {
                let id = id(1)?;
                let new_text = arg(2)?
                    .as_str()
                    .ok_or_else(|| UiError(format!("SET_TEXT needs a string: {op:?}")))?
                    .to_owned();
                let node = self.node_mut(id)?;
                if node.kind != TEXT_NODE {
                    return Err(UiError(format!(
                        "node {id} is a <{}>, not a text node",
                        node.kind
                    )));
                }
                node.text = Some(new_text);
                // The text block containing this node must be measured again.
                text_changed.insert(id);
            }
            opcodes::SET_STYLE => {
                let id = id(1)?;
                let node = self.node_mut(id)?;
                let pairs = &args[2..];
                if pairs.len() % 2 != 0 {
                    return Err(UiError(format!("SET_STYLE needs prop/value pairs: {op:?}")));
                }
                let mut saw_var = false;
                let mut problems = Vec::new();
                for pair in pairs.chunks(2) {
                    let Some(prop) = pair[0].as_str() else {
                        problems.push(format!(
                            "style property name must be a string: {:?}",
                            pair[0]
                        ));
                        continue;
                    };
                    // CSS-wide keywords need the parent: resolved at restyle too.
                    let is_wide = WideKeyword::parse(&pair[1]).is_some();
                    let is_var = prop.starts_with("--")
                        || is_wide
                        || pair[1].as_str().is_some_and(|v| {
                            v.contains("var(") || crate::units::needs_resolution_for(prop, v)
                        });
                    if is_var {
                        // Resolved during restyle, once inherited variables are known.
                        // Without var(), the math can be checked now (with typical units).
                        if let Some(text) =
                            pair[1].as_str().filter(|v| !v.contains("var(") && !is_wide)
                        {
                            let ctx = UnitContext {
                                em: 16.0,
                                rem: 16.0,
                                viewport: (1000.0, 1000.0),
                            };
                            let valid = crate::units::resolve(text, &ctx).is_some_and(|(r, _)| {
                                apply_style(
                                    &mut Style::default(),
                                    &mut Visual::default(),
                                    prop,
                                    &crate::cascade::css_value(&r),
                                )
                                .is_ok()
                            });
                            if !valid && !prop.starts_with("--") {
                                // Like an invalid assignment in the DOM: the old value stays.
                                problems.push(format!("invalid value {text:?} for `{prop}`"));
                                continue;
                            }
                        }
                        saw_var = true;
                    } else if let Err(e) =
                        apply_style(&mut node.style, &mut node.visual, prop, &pair[1])
                    {
                        problems.push(e.to_string());
                        continue;
                    }
                    node.inline.retain(|(p, _)| p != prop);
                    if pair[1] != Value::Null {
                        node.inline.push((prop.to_owned(), pair[1].clone()));
                    }
                    if is_text_prop(prop) {
                        text_style_changed.insert(id);
                    }
                }
                if pairs.chunks(2).any(|p| p[0].as_str() == Some("direction")) {
                    dir_fallback(node);
                }
                let changes = |name| pairs.chunks(2).any(|p| p[0].as_str() == Some(name));
                if pairs
                    .chunks(2)
                    .any(|p| p[0].as_str().is_some_and(|n| n.starts_with("listStyle")))
                {
                    // Inherited: every marker below may change.
                    let mut stack = vec![id];
                    while let Some(n) = stack.pop() {
                        self.markers_dirty.insert(n);
                        stack.extend_from_slice(self.children(n));
                    }
                }
                let node = self.node_mut(id)?;
                if changes("display") || changes("position") {
                    // `contents` and `fixed` move children between layout parents.
                    children_changed.insert(id);
                    children_changed.insert(ROOT);
                }
                if (changes("order") || changes("display") || changes("position"))
                    && let Some(parent) = node.parent
                {
                    // Taffy sees children in `order` order.
                    children_changed.insert(parent);
                }
                styles_changed.insert(id);
                if saw_var {
                    self.uses_vars = true;
                }
                if !self.sheets.is_empty() || self.uses_vars {
                    // Inline styles sit between normal and !important rules.
                    self.style_dirty.insert(id);
                }
                if !problems.is_empty() {
                    return Err(UiError(format!("node {id}: {}", problems.join("; "))));
                }
            }
            opcodes::APPEND_CHILD => {
                let (parent, child) = (id(1)?, id(2)?);
                self.attach(parent, child, None, children_changed)?;
            }
            opcodes::INSERT_BEFORE => {
                let (parent, child, before) = (id(1)?, id(2)?, id(3)?);
                self.attach(parent, child, Some(before), children_changed)?;
            }
            opcodes::REMOVE_CHILD => {
                let (parent, child) = (id(1)?, id(2)?);
                if self.parent(child) != Some(parent) {
                    return Err(UiError(format!("node {child} is not a child of {parent}")));
                }
                self.detach(child, children_changed);
                self.destroy_subtree(child);
            }
            other => return Err(UiError(format!("unknown opcode {other}"))),
        }
        Ok(())
    }

    fn node_mut(&mut self, id: NodeId) -> Result<&mut Node, UiError> {
        self.nodes
            .get_mut(&id)
            .map(|n| &mut **n)
            .ok_or_else(|| UiError(format!("unknown node {id}")))
    }

    fn attach(
        &mut self,
        parent: NodeId,
        child: NodeId,
        before: Option<NodeId>,
        children_changed: &mut HashSet<NodeId>,
    ) -> Result<(), UiError> {
        match self.nodes.get(&parent) {
            None => return Err(UiError(format!("unknown parent {parent}"))),
            Some(p) if p.kind == TEXT_NODE => {
                return Err(UiError(format!("text node {parent} can't have children")));
            }
            Some(_) => {}
        }
        if child == ROOT || !self.nodes.contains_key(&child) {
            return Err(UiError(format!("unknown child {child}")));
        }
        if before == Some(child) {
            return Err(UiError(format!("cannot insert node {child} before itself")));
        }
        // Refuse cycles: `child` must not be `parent` or one of its ancestors.
        let mut cursor = Some(parent);
        while let Some(n) = cursor {
            if n == child {
                return Err(UiError(format!("cannot insert node {child} inside itself")));
            }
            cursor = self.parent(n);
        }
        if let Some(before) = before
            && self.parent(before) != Some(parent)
        {
            return Err(UiError(format!("node {before} is not a child of {parent}")));
        }

        // Moving an attached node: take it out of its old place first.
        self.detach(child, children_changed);

        let after =
            self.children(parent).last().copied().filter(|c| {
                self.nodes.get(c).and_then(|n| n.generated) == Some(PseudoElement::After)
            });
        let siblings = &mut self.nodes.get_mut(&parent).expect("checked").children;
        let index = match before {
            Some(b) => siblings.iter().position(|c| *c == b).expect("checked"),
            // Generated ::after content stays the last child.
            None if after.is_some() => siblings.len() - 1,
            None => siblings.len(),
        };
        siblings.insert(index, child);
        self.nodes.get_mut(&child).expect("checked").parent = Some(parent);
        children_changed.insert(parent);
        Ok(())
    }

    fn detach(&mut self, child: NodeId, children_changed: &mut HashSet<NodeId>) {
        let Some(old_parent) = self.nodes.get_mut(&child).and_then(|n| n.parent.take()) else {
            return;
        };
        if let Some(p) = self.nodes.get_mut(&old_parent) {
            p.children.retain(|c| *c != child);
            children_changed.insert(old_parent);
        }
    }

    fn destroy_subtree(&mut self, id: NodeId) {
        let mut stack = vec![id];
        while let Some(id) = stack.pop() {
            self.scroll.remove(&id);
            self.editors.remove(&id);
            self.unit_uses.remove(&id);
            self.fixed.remove(&id);
            if let Some(node) = self.nodes.remove(&id) {
                stack.extend(node.children);
                self.layout.remove_node(id);
                self.rects.remove(&id);
                self.text_layouts.remove(&id);
                self.ellipses.remove(&id);
                self.dirty_text.remove(&id);
                self.style_dirty.remove(&id);
                self.structure_changed.remove(&id);
            }
        }
    }

    /// Runs layout if anything changed since the last run. Returns whether it ran.
    pub fn layout_if_needed(&mut self) -> bool {
        if !self.needs_layout {
            return false;
        }
        self.restyle_dirty();
        self.refresh_markers();
        // Re-shape text blocks whose content or style changed.
        for root in self.take_dirty_text() {
            let layout = self.build_text_layout(root);
            self.text_layouts.insert(root, layout);
            self.layout.mark_dirty(root);
        }
        let Self {
            layout,
            text_layouts,
            editors,
            nodes,
            image_sizes,
            size,
            ..
        } = self;
        layout.compute(
            ROOT,
            size.0,
            size.1,
            &mut |id, known, available| match text_layouts.get_mut(&id) {
                Some(l) => text::measure(l, known.0, available),
                None => match editors.get(&id) {
                    Some(e) => e.intrinsic_size(known.0),
                    None => {
                        let natural = nodes
                            .get(&id)
                            .and_then(|n| n.attrs.src.as_ref())
                            .and_then(|src| image_sizes.get(src).copied().flatten());
                        image_size(natural.unwrap_or_default(), known)
                    }
                },
            },
        );
        self.rects.clear();
        let mut stack = vec![(ROOT, 0.0_f32, 0.0_f32)];
        while let Some((id, parent_x, parent_y)) = stack.pop() {
            if let Some(node) = self.nodes.get(&id)
                && is_contents(node)
            {
                // No box: its children are placed in the layout parent's space.
                self.rects
                    .insert(id, Rect::new(parent_x, parent_y, 0.0, 0.0));
                stack.extend(node.children.iter().map(|c| (*c, parent_x, parent_y)));
                continue;
            }
            let Some(l) = self.layout.layout(id) else {
                continue;
            };
            let (x, y) = (parent_x + l.x, parent_y + l.y);
            self.rects.insert(id, Rect::new(x, y, l.width, l.height));
            if self.text_layouts.contains_key(&id) {
                // Final line breaking and alignment at the block's real content width.
                let content_width =
                    l.width - l.border[1] - l.border[3] - l.padding[1] - l.padding[3];
                let align = self.computed_text(id).text_align;
                if let Some(layout) = self.text_layouts.get_mut(&id) {
                    text::finish(layout, content_width.max(0.0), align);
                }
            }
            if let Some(node) = self.nodes.get(&id)
                && !is_inline_container(&node.kind)
            {
                // Content moves up/left as its container scrolls; the content may have
                // shrunk since the offset was set, so clamp it first.
                let (sx, sy) = match self.scroll.get_mut(&id) {
                    Some(offset) => {
                        offset.0 = offset.0.clamp(0.0, l.scroll_max[0]);
                        offset.1 = offset.1.clamp(0.0, l.scroll_max[1]);
                        *offset
                    }
                    None => (0.0, 0.0),
                };
                // Inline content inside text is positioned by the text engine.
                stack.extend(node.children.iter().map(|c| {
                    // Fixed nodes are laid out by the root and never scroll.
                    match self.nodes.get(c).is_some_and(|n| is_fixed(*c, n)) {
                        true => (*c, 0.0, 0.0),
                        false => (*c, x - sx, y - sy),
                    }
                }));
            }
        }
        self.refresh_editors();
        self.needs_layout = false;
        true
    }

    /// Restyles, resizes and re-lays out text fields after layout.
    fn refresh_editors(&mut self) {
        let ids: Vec<NodeId> = self.editors.keys().copied().collect();
        for id in ids {
            let style = self.computed_text(id);
            let content = self.content_box(id).unwrap_or_default();
            let Self { editors, text, .. } = self;
            let Some(editor) = editors.get_mut(&id) else {
                continue;
            };
            editor.set_style(&style);
            editor.refresh(text, content.width, content.height);
        }
    }

    /// `id`'s content box (inside borders and padding), where a field's text goes.
    pub fn content_box(&self, id: NodeId) -> Option<Rect> {
        let r = self.rect(id)?;
        let l = self.layout.layout(id)?;
        let [bt, br, bb, bl] = l.border;
        let [pt, pr, pb, pl] = l.padding;
        Some(Rect::new(
            r.x + bl + pl,
            r.y + bt + pt,
            (r.width - bl - br - pl - pr).max(0.0),
            (r.height - bt - bb - pt - pb).max(0.0),
        ))
    }

    /// Sets engine time (ms) for caret blinking.
    pub fn set_time(&mut self, now_ms: f64) {
        self.time_ms = now_ms;
    }

    /// Whether `id` is a text field (`input` or `textarea`).
    pub fn is_editor(&self, id: NodeId) -> bool {
        self.editors.contains_key(&id)
    }

    /// A text field's current text.
    pub fn editor_value(&self, id: NodeId) -> Option<String> {
        self.editors.get(&id).map(Editor::text)
    }

    /// The selected text of a field, if any (for copying).
    pub fn editor_selection(&self, id: NodeId) -> Option<String> {
        self.editors.get(&id).and_then(Editor::selected_text)
    }

    /// Runs a key's editing action on field `id` (`key` and `code` as in the DOM;
    /// `typed` is the text the key types). `None` if `id` isn't an enabled field.
    pub fn editor_key(
        &mut self,
        id: NodeId,
        key: &str,
        code: &str,
        typed: Option<&str>,
        modifiers: Modifiers,
    ) -> Option<KeyOutcome> {
        let attrs = self.attrs(id)?;
        if attrs.disabled {
            return None;
        }
        let read_only = attrs.read_only;
        let now = self.time_ms;
        let Self {
            editors,
            text,
            needs_layout,
            ..
        } = self;
        let editor = editors.get_mut(&id)?;
        let out = editor.key(text, key, code, typed, modifiers, read_only);
        if out.handled {
            editor.touch(now);
            *needs_layout = true;
        }
        Some(out)
    }

    /// Inserts text at field `id`'s caret (paste, IME commit). Returns whether the text
    /// changed; read-only and disabled fields refuse.
    pub fn editor_insert(&mut self, id: NodeId, s: &str) -> bool {
        if self.attrs(id).is_none_or(|a| a.disabled || a.read_only) {
            return false;
        }
        let now = self.time_ms;
        let Self {
            editors,
            text,
            needs_layout,
            ..
        } = self;
        let Some(editor) = editors.get_mut(&id) else {
            return false;
        };
        editor.touch(now);
        *needs_layout = true;
        editor.insert(text, s)
    }

    /// Places the caret or selects in field `id` at absolute (x, y).
    pub fn editor_pointer(&mut self, id: NodeId, x: f32, y: f32, select: PointerSelect) {
        let Some(content) = self.content_box(id) else {
            return;
        };
        let now = self.time_ms;
        let Self {
            editors,
            text,
            needs_layout,
            ..
        } = self;
        if let Some(editor) = editors.get_mut(&id) {
            editor.pointer(text, x - content.x, y - content.y, select);
            editor.touch(now);
            *needs_layout = true;
        }
    }

    /// Updates field `id`'s IME pre-edit text (empty ends composing).
    pub fn editor_compose(&mut self, id: NodeId, preedit: &str, cursor: Option<(usize, usize)>) {
        let now = self.time_ms;
        let Self {
            editors,
            text,
            needs_layout,
            ..
        } = self;
        if let Some(editor) = editors.get_mut(&id) {
            editor.compose(text, preedit, cursor);
            editor.touch(now);
            *needs_layout = true;
        }
    }

    /// Drops field `id`'s IME pre-edit text, if any (focus moved away mid-composition).
    pub fn editor_end_compose(&mut self, id: NodeId) {
        let Self {
            editors,
            text,
            needs_layout,
            ..
        } = self;
        if let Some(editor) = editors.get_mut(&id) {
            editor.end_compose(text);
            *needs_layout = true;
        }
    }

    /// Where field `id`'s IME candidate window should go (absolute logical pixels):
    /// the pre-edit text or the caret.
    pub fn editor_ime_area(&self, id: NodeId) -> Option<Rect> {
        let editor = self.editors.get(&id)?;
        let content = self.content_box(id)?;
        let area = editor.ime_area();
        Some(area.offset(content.x - editor.scroll.0, content.y - editor.scroll.1))
    }

    /// The scroll offset (x, y) of `id`; (0, 0) for elements that never scrolled.
    pub fn scroll_offset(&self, id: NodeId) -> (f32, f32) {
        self.scroll.get(&id).copied().unwrap_or_default()
    }

    /// How far `id`'s content can scroll (x, y), from the last layout.
    pub fn scroll_max(&self, id: NodeId) -> (f32, f32) {
        let m = self
            .layout
            .layout(id)
            .map(|l| l.scroll_max)
            .unwrap_or_default();
        (m[0], m[1])
    }

    /// Which axes of `id` scroll: user scrolling needs `scroll` or `auto`, scripts can
    /// also scroll `hidden`. `clip` and `visible` never scroll.
    pub fn scroll_axes(&self, id: NodeId, by_user: bool) -> [bool; 2] {
        let Some(node) = self.nodes.get(&id) else {
            return [false; 2];
        };
        Overflow::computed(node.visual.overflow).map(|o| match o {
            Overflow::Scroll | Overflow::Auto => true,
            Overflow::Hidden => !by_user,
            Overflow::Visible | Overflow::Clip => false,
        })
    }

    /// Scrolls `id` to (x, y), clamped to its range on the axes it can scroll (see
    /// [`Self::scroll_axes`]; `by_user` limits it to user-scrollable axes). Lays out
    /// first if needed. Returns whether the offset changed.
    pub fn scroll_to(&mut self, id: NodeId, x: f32, y: f32, by_user: bool) -> bool {
        self.layout_if_needed();
        let axes = self.scroll_axes(id, by_user);
        let (max_x, max_y) = self.scroll_max(id);
        let old = self.scroll_offset(id);
        let new = (
            if axes[0] { x.clamp(0.0, max_x) } else { old.0 },
            if axes[1] { y.clamp(0.0, max_y) } else { old.1 },
        );
        if new == old {
            return false;
        }
        self.scroll.insert(id, new);
        // Taffy's layout is cached; only the rects are recomputed.
        self.needs_layout = true;
        true
    }

    /// `id`'s scrollbars (vertical first), for drawing and dragging. A scrollbar shows
    /// on an axis that scrolls by user input when it's `scroll`, or `auto` with content
    /// to scroll, unless `scrollbarWidth: none`. They overlay the content.
    pub fn scrollbars(&self, id: NodeId) -> Vec<Scrollbar> {
        let Some(node) = self.nodes.get(&id) else {
            return Vec::new();
        };
        let thickness = node.visual.scrollbar_width.thickness();
        let (Some(pb), true) = (self.padding_box(id), thickness > 0.0) else {
            return Vec::new();
        };
        let overflow = Overflow::computed(node.visual.overflow);
        let (max_x, max_y) = self.scroll_max(id);
        let (sx, sy) = self.scroll_offset(id);
        let shown =
            |o: Overflow, max: f32| o == Overflow::Scroll || (o == Overflow::Auto && max > 0.0);
        let (show_x, show_y) = (shown(overflow[0], max_x), shown(overflow[1], max_y));
        let (thumb_color, track_color) = self.scrollbar_colors(id);
        let mut bars = Vec::new();
        let thumb_of = |track: Rect, vertical: bool, client: f32, max: f32, offset: f32| {
            let len = if vertical { track.height } else { track.width };
            let size = (len * client / (client + max)).max(len.min(SCROLLBAR_MIN_THUMB));
            let at = if max > 0.0 {
                (len - size) * offset / max
            } else {
                0.0
            };
            if vertical {
                Rect::new(track.x, track.y + at, track.width, size)
            } else {
                Rect::new(track.x + at, track.y, size, track.height)
            }
        };
        let gap = SCROLLBAR_MARGIN;
        if show_y {
            let corner = if show_x { thickness + gap } else { 0.0 };
            let track = Rect::new(
                pb.x + pb.width - thickness - gap,
                pb.y + gap,
                thickness,
                (pb.height - 2.0 * gap - corner).max(0.0),
            );
            bars.push(Scrollbar {
                node: id,
                vertical: true,
                thumb: thumb_of(track, true, pb.height, max_y, sy),
                track,
                thumb_color,
                track_color,
            });
        }
        if show_x {
            let corner = if show_y { thickness + gap } else { 0.0 };
            let track = Rect::new(
                pb.x + gap,
                pb.y + pb.height - thickness - gap,
                (pb.width - 2.0 * gap - corner).max(0.0),
                thickness,
            );
            bars.push(Scrollbar {
                node: id,
                vertical: false,
                thumb: thumb_of(track, false, pb.width, max_x, sx),
                track,
                thumb_color,
                track_color,
            });
        }
        bars
    }

    /// The scrollbar under (x, y) among `path`'s elements (innermost first), if any.
    /// The hit area is the track plus its margin, so thin bars are easy to grab.
    pub fn scrollbar_at(&self, path: &[NodeId], x: f32, y: f32) -> Option<Scrollbar> {
        path.iter().find_map(|id| {
            self.scrollbars(*id).into_iter().find(|bar| {
                let area = bar.track.expand(SCROLLBAR_MARGIN);
                x >= area.x && y >= area.y && x < area.x + area.width && y < area.y + area.height
            })
        })
    }

    /// `scrollbarColor` (inherited): thumb and track colours.
    fn scrollbar_colors(&self, id: NodeId) -> (Rgba, Rgba) {
        let mut at = Some(id);
        while let Some(node) = at.and_then(|id| self.nodes.get(&id)) {
            match node.visual.scrollbar_color {
                Some(Some(colors)) => return colors,
                Some(None) => break,
                None => at = node.parent,
            }
        }
        (SCROLLBAR_THUMB, Rgba::TRANSPARENT)
    }

    /// `id`'s padding box (its border box minus borders), where content scrolls.
    pub fn padding_box(&self, id: NodeId) -> Option<Rect> {
        let r = self.rect(id)?;
        let [t, right, b, l] = self.layout.layout(id)?.border;
        Some(Rect::new(
            r.x + l,
            r.y + t,
            (r.width - l - right).max(0.0),
            (r.height - t - b).max(0.0),
        ))
    }

    /// The node's absolute rect from the most recent layout.
    pub fn rect(&self, id: NodeId) -> Option<Rect> {
        self.rects.get(&id).copied()
    }

    /// The topmost element under the point (x, y) in logical pixels, or `None` if
    /// the point only hits the root. Lays out first if needed.
    ///
    /// Elements are tested in reverse paint order: later siblings before earlier ones,
    /// children before their parent (children outside their parent's box still hit).
    /// Rounded corners are respected; `display: none` subtrees and elements with
    /// `pointerEvents: none` (inherited) are skipped, though their children can opt
    /// back in with `pointerEvents: auto`. Text inside a text element hits the text
    /// element; `::before`/`::after` content hits the element that generated it.
    pub fn hit_test(&mut self, x: f32, y: f32) -> Option<NodeId> {
        self.layout_if_needed();
        // Fixed nodes paint above the tree, so they're tested first.
        for id in self.fixed_paint_order().iter().rev() {
            let inherited = self.pointer_events_of(self.parent(*id));
            let visible = self.computed_text(*id).visible;
            if let Some(hit) = self.hit(*id, x, y, inherited, visible, TransformContext::ROOT) {
                return Some(hit);
            }
        }
        self.hit(ROOT, x, y, true, true, TransformContext::ROOT)
    }

    /// `node`'s own 4×4 transform (with its parent's `perspective`), if it has one.
    fn node_matrix(&self, node: &Node, rect: Rect) -> Option<Mat4> {
        let t = node.visual.transform.as_ref()?;
        let m = t.spec.matrix(rect, t.origin)?;
        // The parent's `perspective` applies to its transformed children.
        let parent = node
            .parent
            .and_then(|p| Some((self.nodes.get(&p)?, self.rects.get(&p)?)));
        match parent {
            Some((p, prect)) => match p
                .visual
                .transform
                .as_ref()
                .and_then(|t| Some((t.perspective?, t.perspective_origin)))
            {
                Some((d, (ox, oy))) => {
                    let (ox, oy) = (
                        prect.x + ox.resolve(prect.width),
                        prect.y + oy.resolve(prect.height),
                    );
                    Some(
                        Mat4::translate(ox, oy, 0.0)
                            .mul(&Mat4::perspective(d))
                            .mul(&Mat4::translate(-ox, -oy, 0.0))
                            .mul(&m),
                    )
                }
                None => Some(m),
            },
            None => Some(m),
        }
    }

    /// The plane `node` draws in, and the context for its children: `None` when it's
    /// a back-facing `backface-visibility: hidden` element (not drawn or hit).
    fn transform_step(
        &self,
        node: &Node,
        rect: Rect,
        xf: TransformContext,
    ) -> Option<(Homography, TransformContext, bool)> {
        let own = self.node_matrix(node, rect);
        let acc = match &own {
            Some(m) => xf.pending.mul(m),
            None => xf.pending,
        };
        let t = node.visual.transform.as_deref();
        if t.is_some_and(|t| t.backface_hidden) && acc.is_backface() {
            return None;
        }
        let plane = if acc.is_identity() {
            xf.world
        } else {
            xf.world.mul(&acc.flatten())
        };
        let child = if t.is_some_and(|t| t.preserve_3d) {
            TransformContext {
                world: xf.world,
                pending: acc,
            }
        } else {
            TransformContext {
                world: plane,
                pending: Mat4::IDENTITY,
            }
        };
        Some((plane, child, own.is_some()))
    }

    /// Whether pointer events are enabled for `id` (inherited `pointerEvents`).
    fn pointer_events_of(&self, id: Option<NodeId>) -> bool {
        let mut at = id;
        while let Some(node) = at.and_then(|id| self.nodes.get(&id)) {
            if let Some(enabled) = node.visual.pointer_events {
                return enabled;
            }
            at = node.parent;
        }
        true
    }

    /// `x`, `y` are window coordinates; each element maps them into its own plane.
    fn hit(
        &self,
        id: NodeId,
        x: f32,
        y: f32,
        inherited: bool,
        visible: bool,
        xf: TransformContext,
    ) -> Option<NodeId> {
        let (wx, wy) = (x, y);
        let node = self.nodes.get(&id)?;
        if node.style.display == Display::None {
            return None;
        }
        // `visibility: hidden` elements can't be hit, but visible children can.
        let shown = node.visual.text.visible.unwrap_or(visible);
        if is_contents(node) {
            let enabled = node.visual.pointer_events.unwrap_or(inherited);
            return self
                .paint_order(node)
                .iter()
                .rev()
                .filter(|c| !self.nodes.get(c).is_some_and(|n| is_fixed(**c, n)))
                .find_map(|c| self.hit(*c, wx, wy, enabled, shown, xf));
        }
        let rect = *self.rects.get(&id)?;
        let (plane, child_xf, _) = self.transform_step(node, rect, xf)?;
        let (x, y) = if plane.is_identity() {
            (wx, wy)
        } else {
            plane.inverse()?.apply(wx, wy)?
        };
        let radii = resolve_radii(&node.visual.border_radius, rect.width, rect.height);
        // Hit testing matches what's drawn: clipped-away parts can't be hit.
        let l = self.layout.layout(id).unwrap_or_default();
        if self
            .self_clips(node, rect, &l, radii)
            .iter()
            .any(|clip| !clip.contains(x, y))
        {
            return None;
        }
        let enabled = node.visual.pointer_events.unwrap_or(inherited);
        let children_visible =
            overflow_clip(&node.visual, rect, &l, radii).is_none_or(|clip| clip.contains(x, y));
        if !is_inline_container(&node.kind) && children_visible {
            for child in self.paint_order(node).iter().rev() {
                if self.nodes.get(child).is_some_and(|n| is_fixed(*child, n)) {
                    continue;
                }
                if let Some(hit) = self.hit(*child, wx, wy, enabled, shown, child_xf) {
                    return Some(hit);
                }
            }
        }
        if !enabled || !shown || id == ROOT {
            return None;
        }
        if !rect.contains_rounded(radii, x, y) {
            return None;
        }
        // Generated content belongs to its originating element.
        match node.generated {
            Some(_) => node.parent.filter(|p| *p != ROOT),
            None => Some(id),
        }
    }

    /// Whether `id` is rendered: it exists and neither it nor an ancestor is
    /// `display: none`.
    pub fn is_displayed(&self, id: NodeId) -> bool {
        let mut at = Some(id);
        while let Some(id) = at {
            let Some(node) = self.nodes.get(&id) else {
                return false;
            };
            if node.style.display == Display::None {
                return false;
            }
            at = node.parent;
        }
        true
    }

    /// The CSS cursor to show over `id` (or over nothing for `None`): the nearest
    /// `cursor` set on it or an ancestor, with `auto` meaning `text` over text elements
    /// and `default` elsewhere.
    pub fn cursor(&self, id: Option<NodeId>) -> &'static str {
        let auto = match id.and_then(|id| self.nodes.get(&id)) {
            Some(node) if is_inline_container(&node.kind) || is_editor_kind(&node.kind) => "text",
            _ => "default",
        };
        let mut at = id;
        while let Some(node) = at.and_then(|id| self.nodes.get(&id)) {
            match node.visual.cursor {
                None => at = node.parent,
                Some("auto") => return auto,
                Some(cursor) => return cursor,
            }
        }
        auto
    }

    /// The event path of `target`: the target first, then each ancestor up to (not
    /// including) the root.
    pub fn event_path(&self, target: NodeId) -> Vec<NodeId> {
        let mut path = Vec::new();
        let mut at = Some(target);
        while let Some(id) = at.filter(|id| *id != ROOT && self.nodes.contains_key(id)) {
            path.push(id);
            at = self.nodes[&id].parent;
        }
        path
    }

    /// Lays out if needed, then lists the paint commands for the whole tree.
    ///
    /// Per node, in order (matching CSS painting): `BackdropBlur` (if any), then
    /// `PushLayer` when the node needs one (a `filter` blur, or group opacity over
    /// more than one command), then outer `BoxShadow`s, the `Quad`, `InsetShadow`s,
    /// the children, and `PopLayer`. `display: none` and fully transparent subtrees
    /// are skipped. A node with opacity but nothing to group just scales its alpha.
    pub fn draw_list(&mut self) -> Vec<DrawCmd> {
        self.layout_if_needed();
        let mut out = Vec::new();
        self.collect(
            ROOT,
            &ComputedText::default(),
            TransformContext::ROOT,
            &mut out,
        );
        // Fixed nodes paint last, outside their ancestors' clips and layers.
        for id in self.fixed_paint_order() {
            let text = match self.parent(id) {
                Some(p) => self.computed_text(p),
                None => ComputedText::default(),
            };
            self.collect(id, &text, TransformContext::ROOT, &mut out);
        }
        out
    }

    fn collect(
        &self,
        id: NodeId,
        inherited: &ComputedText,
        xf: TransformContext,
        out: &mut Vec<DrawCmd>,
    ) {
        let Some(node) = self.nodes.get(&id) else {
            return;
        };
        let v = &node.visual;
        if node.style.display == Display::None || v.opacity <= 0.0 {
            return;
        }
        if is_contents(node) {
            let text = inherited.child(&v.text);
            for child in self.paint_order(node).iter() {
                if !self.nodes.get(child).is_some_and(|n| is_fixed(*child, n)) {
                    self.collect(*child, &text, xf, out);
                }
            }
            return;
        }
        let (Some(&rect), Some(l)) = (self.rects.get(&id), self.layout.layout(id)) else {
            return;
        };
        let Some((plane, child_xf, transformed)) = self.transform_step(node, rect, xf) else {
            return;
        };
        let radii = resolve_radii(&v.border_radius, rect.width, rect.height);
        let text = inherited.child(&v.text);
        // `currentColor` resolves to this node's computed text colour.
        let current = |color: Rgba, is_current: bool| if is_current { text.color } else { color };

        let mut own = Vec::new();
        let shadow = |s: &Shadow| ShadowShape {
            rect,
            radii,
            offset_x: s.offset_x,
            offset_y: s.offset_y,
            blur: s.blur,
            spread: s.spread,
            color: current(s.color, s.current_color),
        };
        // CSS paints the first shadow on top, so draw the list back to front.
        for s in v
            .shadows
            .iter()
            .rev()
            .filter(|s| !s.inset && current(s.color, s.current_color).a > 0.0)
        {
            own.push(DrawCmd::BoxShadow(shadow(s)));
        }
        let (images, text_fill) = background_layers(v, rect, radii, &l, text.pixelated);
        let mut background = current(v.background, v.background_current);
        // The colour is clipped like the bottom layer.
        let bottom = v.background_images.len().max(1) - 1;
        let colour_clip = v.background_clips[bottom % v.background_clips.len()];
        match colour_clip {
            BackgroundClip::BorderBox => {}
            BackgroundClip::Text => background = Rgba::TRANSPARENT,
            clip => {
                let (area, area_radii) = clip_area(clip, rect, radii, &l);
                if background.a > 0.0 && !area.is_empty() {
                    own.push(DrawCmd::Quad(Quad {
                        rect: area,
                        background,
                        images: Vec::new(),
                        border_color: Rgba::TRANSPARENT,
                        border: [0.0; 4],
                        radii: area_radii,
                    }));
                }
                background = Rgba::TRANSPARENT;
            }
        }
        let colors = [0, 1, 2, 3].map(|i| current(v.border_colors[i], v.border_currents[i]));
        let border_image = v
            .border_image
            .as_ref()
            .filter(|image| image.source.is_some());
        // One solid colour all round is drawn by the quad itself; a border image
        // replaces the border.
        let simple_border = border_image.is_none()
            && v.border_styles.iter().all(|s| *s == BorderStyle::Solid)
            && colors.iter().all(|c| *c == colors[0]);
        let quad = Quad {
            rect,
            background,
            images,
            border_color: if simple_border {
                colors[0]
            } else {
                Rgba::TRANSPARENT
            },
            border: l.border,
            radii,
        };
        let blends = &v.background_blends;
        if quad.is_visible()
            && !quad.images.is_empty()
            && blends.iter().any(|b| *b != BlendMode::Normal)
        {
            blended_background(quad, v, &mut own);
        } else if quad.is_visible() {
            own.push(DrawCmd::Quad(quad));
        }
        let drawn =
            |i: usize| l.border[i] > 0.0 && colors[i].a > 0.0 && v.border_styles[i].is_visible();
        if let Some(image) = border_image {
            own.push(DrawCmd::BorderImage {
                area: image.area(rect, l.border),
                border: l.border,
                image: image.clone(),
                pixelated: text.pixelated,
            });
        } else if !simple_border && (0..4).any(drawn) {
            own.push(DrawCmd::Border {
                rect,
                radii,
                widths: l.border,
                colors,
                styles: v.border_styles,
            });
        }
        for s in v
            .shadows
            .iter()
            .rev()
            .filter(|s| s.inset && current(s.color, s.current_color).a > 0.0)
        {
            own.push(DrawCmd::InsetShadow {
                shadow: shadow(s),
                border: l.border,
            });
        }
        if node.kind == IMAGE
            && let Some(src) = &node.attrs.src
        {
            self.draw_image(src, v, (rect, radii), &l, text.pixelated, &mut own);
        }
        // `visibility: hidden`: nothing of the box itself (its text runs carry their own
        // visibility, so visible spans inside still draw).
        if !text.visible {
            own.clear();
        }
        if let Some(layout) = self.text_layouts.get(&id) {
            let origin = (
                rect.x + l.border[3] + l.padding[3],
                rect.y + l.border[0] + l.padding[0],
            );
            let content_width =
                rect.width - l.border[1] - l.border[3] - l.padding[1] - l.padding[3];
            // Cut lines short only where the overflow is clipped, as CSS does.
            let clips_x = Overflow::computed(v.overflow)[0] != Overflow::Visible;
            let mut cmd = match self.ellipses.get(&id).filter(|_| clips_x) {
                Some(dots) => text::draw_ellipsized(
                    layout,
                    origin,
                    text::Ellipsis {
                        layout: dots,
                        width: content_width,
                        rtl: text.direction == Direction::Rtl,
                    },
                ),
                None => text::draw(layout, origin),
            };
            cmd.fill = text_fill.map(|image| (image, rect));
            if !cmd.runs.is_empty() || !cmd.decorations.is_empty() {
                // Text shadows: tinted copies under the text, last shadow lowest.
                for s in text.text_shadow.iter().rev() {
                    let color = current(s.color, s.current_color);
                    if color.a <= 0.0 {
                        continue;
                    }
                    let copy = cmd.shadow(s.offset_x, s.offset_y, color);
                    if s.blur > 0.0 {
                        // Same blur radius meaning as box shadows: sigma is half of it.
                        let sigma = s.blur / 2.0;
                        own.push(DrawCmd::PushLayer {
                            bounds: copy.bounds.expand(3.0 * sigma),
                            blur: sigma,
                            opacity: 1.0,
                            blend: BlendMode::Normal,
                            matrix: None,
                            shadows: Vec::new(),
                        });
                        own.push(DrawCmd::Text(copy));
                        own.push(DrawCmd::PopLayer);
                    } else {
                        own.push(DrawCmd::Text(copy));
                    }
                }
                own.push(DrawCmd::Text(cmd));
            }
        }

        if let Some(editor) = self.editors.get(&id)
            && text.visible
        {
            self.editor_cmds(editor, node, rect, &l, radii, &text, &mut own);
        }

        // clip-path (and legacy `clip`) clip the element and everything inside it;
        // `overflow` clips only the children, to the padding box.
        if transformed {
            out.push(DrawCmd::PushTransform(plane));
        }
        let self_clips = self.self_clips(node, rect, &l, radii);
        for clip in &self_clips {
            out.push(DrawCmd::PushClip(clip.clone()));
        }
        let overflow_clip = overflow_clip(v, rect, &l, radii);

        if text.visible && (v.backdrop_blur > 0.0 || v.backdrop_matrix.is_some()) {
            out.push(DrawCmd::BackdropBlur {
                rect,
                radii,
                blur: v.backdrop_blur,
                matrix: v.backdrop_matrix,
            });
        }

        let outline = outline(v, rect, radii, text.color).filter(|_| text.visible);
        let own_count = own.len() + usize::from(outline.is_some());
        let group_opacity = v.opacity < 1.0 && (!node.children.is_empty() || own_count > 1);
        let shadows: Vec<LayerShadow> = v
            .drop_shadows
            .iter()
            .map(|s| LayerShadow {
                offset_x: s.offset_x,
                offset_y: s.offset_y,
                sigma: s.blur / 2.0,
                color: if s.current_color { text.color } else { s.color },
            })
            .filter(|s| s.color.a > 0.0)
            .collect();
        let masked = v.mask_images.iter().any(Option::is_some);
        if v.filter_blur > 0.0
            || group_opacity
            || v.mix_blend != BlendMode::Normal
            || v.filter_matrix.is_some()
            || !shadows.is_empty()
            || masked
        {
            let start = out.len();
            let shadow_reach = shadows.clone();
            out.push(DrawCmd::PushLayer {
                bounds: rect,
                blur: v.filter_blur,
                opacity: v.opacity,
                blend: v.mix_blend,
                matrix: v.filter_matrix,
                shadows,
            });
            out.extend(own);
            self.collect_children(node, &text, overflow_clip, child_xf, out);
            self.collect_scrollbars(id, out);
            out.extend(outline);
            // The layer must cover everything drawn into it, plus the blur's spread.
            let content = out[start + 1..]
                .iter()
                .filter_map(DrawCmd::bounds)
                .fold(rect, Rect::union);
            // Drop shadows reach past it by their offset and blur.
            let mut reach = content.expand(3.0 * v.filter_blur);
            for s in &shadow_reach {
                reach = reach.union(reach.offset(s.offset_x, s.offset_y).expand(3.0 * s.sigma));
            }
            if let DrawCmd::PushLayer { bounds, .. } = &mut out[start] {
                *bounds = reach;
            }
            if masked {
                out.push(DrawCmd::BeginMask(v.mask_modes[0]));
                out.push(DrawCmd::Quad(Quad {
                    rect,
                    background: Rgba::TRANSPARENT,
                    images: mask_layers(v, rect, text.pixelated),
                    border_color: Rgba::TRANSPARENT,
                    border: [0.0; 4],
                    radii: Radii::ZERO,
                }));
            }
            out.push(DrawCmd::PopLayer);
        } else {
            if v.opacity < 1.0 {
                for cmd in &mut own {
                    cmd.scale_alpha(v.opacity);
                }
            }
            out.extend(own);
            self.collect_children(node, &text, overflow_clip, child_xf, out);
            self.collect_scrollbars(id, out);
            if let Some(mut outline) = outline {
                if v.opacity < 1.0 {
                    outline.scale_alpha(v.opacity);
                }
                out.push(outline);
            }
        }
        for _ in &self_clips {
            out.push(DrawCmd::PopClip);
        }
        if transformed {
            out.push(DrawCmd::PopTransform);
        }
    }

    fn collect_children(
        &self,
        node: &Node,
        text: &ComputedText,
        clip: Option<ClipShape>,
        xf: TransformContext,
        out: &mut Vec<DrawCmd>,
    ) {
        if node.children.is_empty() {
            return;
        }
        let clipped = clip.is_some();
        if let Some(clip) = clip {
            out.push(DrawCmd::PushClip(clip));
        }
        for child in self.paint_order(node).iter() {
            if !self.nodes.get(child).is_some_and(|n| is_fixed(*child, n)) {
                self.collect(*child, text, xf, out);
            }
        }
        if clipped {
            out.push(DrawCmd::PopClip);
        }
    }

    /// The children Taffy lays out in `node`, in document order, stably sorted by
    /// `order`: `display: contents` children are replaced by their own children,
    /// and fixed children are left to the root.
    fn layout_order(&self, node: &Node) -> Vec<NodeId> {
        let mut out = Vec::with_capacity(node.children.len());
        self.flatten_contents(node, &mut out);
        out.sort_by_key(|id| self.nodes.get(id).map_or(0, |n| n.visual.order));
        out
    }

    fn flatten_contents(&self, node: &Node, out: &mut Vec<NodeId>) {
        for c in &node.children {
            match self.nodes.get(c) {
                Some(child) if is_fixed(*c, child) => {}
                Some(child) if is_contents(child) => self.flatten_contents(child, out),
                _ => out.push(*c),
            }
        }
    }

    /// Sends `id`'s layout children to Taffy. A `display: contents` node has none: its
    /// layout parent takes them. The root also lays out every fixed node.
    fn set_layout_children(&mut self, id: NodeId) {
        let Some(node) = self.nodes.get(&id) else {
            return;
        };
        if is_inline_container(&node.kind) {
            // Spans and text nodes inside are laid out by the text engine.
            self.layout.set_children(id, &[]);
            return;
        }
        if is_contents(node) {
            self.layout.set_children(id, &[]);
            if let Some(parent) = node.parent {
                self.set_layout_children(parent);
            }
            return;
        }
        let mut children = self.layout_order(node);
        if id == ROOT {
            children.extend(self.fixed_nodes(false));
        }
        self.layout.set_children(id, &children);
    }

    /// The image of an `image` element, fitted into its content box by `objectFit` and
    /// `objectPosition`, clipped to the box's inner rounded corners.
    fn draw_image(
        &self,
        src: &str,
        v: &Visual,
        (rect, radii): (Rect, Radii),
        l: &NodeLayout,
        pixelated: bool,
        out: &mut Vec<DrawCmd>,
    ) {
        let inset = [0, 1, 2, 3].map(|i| l.border[i] + l.padding[i]);
        let content = Rect::new(
            rect.x + inset[3],
            rect.y + inset[0],
            (rect.width - inset[1] - inset[3]).max(0.0),
            (rect.height - inset[0] - inset[2]).max(0.0),
        );
        if content.is_empty() {
            return;
        }
        // Until the app reports the natural size, fit as if it matched the box.
        let natural = self
            .image_sizes
            .get(src)
            .copied()
            .flatten()
            .unwrap_or((content.width, content.height));
        let size = v
            .object_fit
            .background_size(natural, (content.width, content.height));
        out.push(DrawCmd::PushClip(inner_corners(content, radii, inset)));
        out.push(DrawCmd::Quad(Quad {
            rect: content,
            background: Rgba::TRANSPARENT,
            images: vec![ImageFill {
                image: Arc::new(BackgroundImage::Url(src.to_owned())),
                size,
                position: v.object_position,
                repeat: BackgroundRepeat::NO_REPEAT,
                area: content,
                radii: Radii::ZERO,
                pixelated,
            }],
            border_color: Rgba::TRANSPARENT,
            border: [0.0; 4],
            radii: Radii::ZERO,
        }));
        out.push(DrawCmd::PopClip);
    }

    /// Asks the app for an image's natural size, once per `src`.
    fn request_image(&mut self, src: &str) {
        if !self.image_sizes.contains_key(src) && !self.image_requests.iter().any(|r| r == src) {
            self.image_requests.push(src.to_owned());
        }
    }

    /// Image `src`s the app should load and report with [`Self::set_image_size`].
    pub fn take_image_requests(&mut self) -> Vec<String> {
        std::mem::take(&mut self.image_requests)
    }

    /// Records an image's natural size in pixels (`None` if it couldn't be loaded)
    /// and re-lays out the `image` elements showing it.
    pub fn set_image_size(&mut self, src: &str, size: Option<(u32, u32)>) {
        let size = size.map(|(w, h)| (w as f32, h as f32));
        if self.image_sizes.insert(src.to_owned(), size) == Some(size) {
            return;
        }
        let users: Vec<NodeId> = self
            .nodes
            .iter()
            .filter(|(_, n)| n.kind == IMAGE && n.attrs.src.as_deref() == Some(src))
            .map(|(id, _)| *id)
            .collect();
        for id in users {
            self.layout.mark_dirty(id);
            self.needs_layout = true;
        }
    }

    /// Keeps the set of fixed nodes in step with `id`'s style.
    fn update_fixed(&mut self, id: NodeId) {
        match self.nodes.get(&id) {
            Some(node) if is_fixed(id, node) => self.fixed.insert(id),
            _ => self.fixed.remove(&id),
        };
    }

    /// Fixed nodes attached to the tree, in document order. With `rendered_only`,
    /// those inside `display: none` or fully transparent subtrees are left out.
    fn fixed_nodes(&self, rendered_only: bool) -> Vec<NodeId> {
        let mut out = Vec::new();
        if self.fixed.is_empty() {
            return out;
        }
        let mut stack = vec![ROOT];
        while let Some(id) = stack.pop() {
            let Some(node) = self.nodes.get(&id) else {
                continue;
            };
            if rendered_only && (node.style.display == Display::None || node.visual.opacity <= 0.0)
            {
                continue;
            }
            if self.fixed.contains(&id) {
                out.push(id);
            }
            stack.extend(node.children.iter().rev());
        }
        out
    }

    /// Rendered fixed nodes in paint order: by `zIndex`, then document order.
    fn fixed_paint_order(&self) -> Vec<NodeId> {
        let mut fixed = self.fixed_nodes(true);
        fixed.sort_by_key(|id| {
            self.nodes
                .get(id)
                .map_or(0, |n| n.visual.z_index.unwrap_or(0))
        });
        fixed
    }

    /// Children in paint order (hit testing goes in reverse): by `zIndex` (auto is 0),
    /// then `order`, then document order. Iron treats each z-indexed element as its
    /// own stacking context: z-index orders siblings, not across ancestors.
    fn paint_order<'a>(&self, node: &'a Node) -> std::borrow::Cow<'a, [NodeId]> {
        let key = |id: &NodeId| {
            self.nodes
                .get(id)
                .map_or((0, 0), |n| (n.visual.z_index.unwrap_or(0), n.visual.order))
        };
        if node.children.iter().all(|c| key(c) == (0, 0)) {
            return std::borrow::Cow::Borrowed(&node.children);
        }
        let mut sorted = node.children.clone();
        sorted.sort_by_key(key);
        std::borrow::Cow::Owned(sorted)
    }

    /// A text field's content: selection, text (or placeholder) and the blinking
    /// caret, clipped to the padding box and shifted by the field's own scroll.
    #[allow(clippy::too_many_arguments)]
    fn editor_cmds(
        &self,
        editor: &Editor,
        node: &Node,
        rect: Rect,
        l: &NodeLayout,
        radii: Radii,
        text: &ComputedText,
        out: &mut Vec<DrawCmd>,
    ) {
        let [bt, br, bb, bl] = l.border;
        let [pt, _, _, pl] = l.padding;
        let padding_box = Rect::new(
            rect.x + bl,
            rect.y + bt,
            (rect.width - bl - br).max(0.0),
            (rect.height - bt - bb).max(0.0),
        );
        let origin = (
            padding_box.x + pl - editor.scroll.0,
            padding_box.y + pt - editor.scroll.1,
        );
        let quad = |r: Rect, color: Rgba| {
            DrawCmd::Quad(Quad {
                rect: r.offset(origin.0, origin.1),
                background: color,
                images: Vec::new(),
                border_color: Rgba::TRANSPARENT,
                border: [0.0; 4],
                radii: Radii::ZERO,
            })
        };
        out.push(DrawCmd::PushClip(inner_corners(
            padding_box,
            radii,
            l.border,
        )));
        let focused = node.state.focus && !node.attrs.disabled;
        if focused {
            out.extend(
                editor
                    .selection_rects()
                    .into_iter()
                    .map(|r| quad(r, crate::editor::SELECTION)),
            );
        }
        let placeholder = editor
            .placeholder_layout()
            .map(|l| (l, editor.placeholder_x()));
        if let Some((layout, dx)) = placeholder.or(editor.layout().map(|l| (l, 0.0))) {
            let cmd = text::draw(layout, (origin.0 + dx, origin.1));
            if !cmd.runs.is_empty() || !cmd.decorations.is_empty() {
                out.push(DrawCmd::Text(cmd));
            }
        }
        if focused
            && editor.caret_on(self.time_ms)
            && let Some(caret) = editor.caret_rect()
        {
            out.push(quad(caret, text.caret_color.unwrap_or(text.color)));
        }
        out.push(DrawCmd::PopClip);
    }

    /// Scrollbars draw over the content, as rounded thumbs on optional tracks.
    fn collect_scrollbars(&self, id: NodeId, out: &mut Vec<DrawCmd>) {
        for bar in self.scrollbars(id) {
            let radius = bar.track.width.min(bar.track.height) / 2.0;
            for (rect, color) in [(bar.track, bar.track_color), (bar.thumb, bar.thumb_color)] {
                if color.a > 0.0 {
                    out.push(DrawCmd::Quad(Quad {
                        rect,
                        background: color,
                        images: Vec::new(),
                        border_color: Rgba::TRANSPARENT,
                        border: [0.0; 4],
                        radii: Radii::circular([radius; 4]),
                    }));
                }
            }
        }
    }

    /// The clips on an element itself: `clipPath`, and `clip: rect()` for absolutely
    /// positioned elements.
    fn self_clips(&self, node: &Node, rect: Rect, l: &NodeLayout, radii: Radii) -> Vec<ClipShape> {
        let v = &node.visual;
        let mut clips = Vec::new();
        if let Some(edges) = v.clip_rect
            && node.style.position == Position::Absolute
        {
            let [top, right, bottom, left] = edges;
            let (x0, y0) = (left.unwrap_or(0.0), top.unwrap_or(0.0));
            let x1 = right.unwrap_or(rect.width);
            let y1 = bottom.unwrap_or(rect.height);
            clips.push(ClipShape::rect(Rect::new(
                rect.x + x0,
                rect.y + y0,
                (x1 - x0).max(0.0),
                (y1 - y0).max(0.0),
            )));
        }
        if let Some(path) = &v.clip_path {
            clips.push(path.resolve(rect, l.border, l.padding, radii));
        }
        clips
    }
}

/// A scrollbar of a scroll container, in absolute logical pixels.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Scrollbar {
    pub node: NodeId,
    pub vertical: bool,
    pub track: Rect,
    pub thumb: Rect,
    pub thumb_color: Rgba,
    pub track_color: Rgba,
}

/// Space between a scrollbar and the padding box edge.
const SCROLLBAR_MARGIN: f32 = 2.0;
/// The thumb never gets shorter than this (unless the track is).
const SCROLLBAR_MIN_THUMB: f32 = 24.0;
/// Default thumb colour: visible on light and dark backgrounds.
const SCROLLBAR_THUMB: Rgba = Rgba {
    r: 0.55,
    g: 0.57,
    b: 0.62,
    a: 0.6,
};

/// Far enough to never matter: the clip edge on an axis that doesn't clip.
const UNCLIPPED: f32 = 1.0e7;

/// The clip `overflow` puts on an element's children: its padding box with inner
/// corner radii. An axis that doesn't clip (`overflow: clip visible`) is unbounded.
fn overflow_clip(v: &Visual, rect: Rect, l: &NodeLayout, radii: Radii) -> Option<ClipShape> {
    let [x, y] = Overflow::computed(v.overflow);
    if !x.clips() && !y.clips() {
        return None;
    }
    let [bt, br, bb, bl] = l.border;
    let padding_box = Rect::new(
        rect.x + bl,
        rect.y + bt,
        (rect.width - bl - br).max(0.0),
        (rect.height - bt - bb).max(0.0),
    );
    let mut clip = inner_corners(padding_box, radii, l.border);
    if !x.clips() {
        clip.rect.x = -UNCLIPPED;
        clip.rect.width = 2.0 * UNCLIPPED;
    }
    if !y.clips() {
        clip.rect.y = -UNCLIPPED;
        clip.rect.height = 2.0 * UNCLIPPED;
    }
    if !(x.clips() && y.clips()) {
        clip.radii_x = [0.0; 4];
        clip.radii_y = [0.0; 4];
    }
    Some(clip)
}

fn root_style(width: f32, height: f32) -> Style {
    Style {
        size: Size {
            width: Dimension::length(width),
            height: Dimension::length(height),
        },
        ..Style::default()
    }
}

fn node_id(v: &Value) -> Result<NodeId, UiError> {
    match v.as_f64() {
        Some(n) if n >= 0.0 && n.fract() == 0.0 && n <= f64::from(u32::MAX) => Ok(NodeId(n as u32)),
        _ => Err(UiError(format!("invalid node id {v:?}"))),
    }
}

