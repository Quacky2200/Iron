/// The root container every React root renders into.
pub const ROOT: NodeId = NodeId(0);

/// First id used for `::before`/`::after` nodes; React allocates ids from 1 upwards.
const FIRST_GENERATED_ID: u32 = 0x8000_0000;

/// A problem with one op. The op is skipped; the tree stays valid.
#[derive(Clone, Debug, PartialEq)]
pub struct UiError(pub String);

impl fmt::Display for UiError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for UiError {}

struct Node {
    kind: String,
    parent: Option<NodeId>,
    children: Vec<NodeId>,
    style: Style,
    visual: Visual,
    /// The characters of a `#text` node.
    text: Option<String>,
    attrs: Attrs,
    state: ElementState,
    /// Inline `style` declarations in the order they were set (latest value wins).
    inline: Vec<(String, Value)>,
    /// Set for `::before` / `::after` content generated by stylesheets.
    generated: Option<PseudoElement>,
    /// Computed custom properties (`--name`), inherited from the parent.
    vars: Rc<Vars>,
}

